//! Reverse engineering of the compiler's own C: a machine generated, read
//! back and generated again gives the same C. That equality is the proof the
//! recovery relies on, so it is what these tests ask for.

use arclang::compiler::recover::{self, Generated};
use arclang::{Compiler, CompilerConfig};
use std::path::Path;

/// The C of an example: (header name, header, code name, code).
fn generated_c(example: &str) -> Option<(String, String, String, String)> {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join(example);
    let result = Compiler::new(CompilerConfig::default()).compile_file(&path).ok()?;
    let (files, _) = arclang::compiler::embedded::export(&result.ast).ok()?;
    let header = files.iter().find(|(name, text)| name.ends_with(".h") && text.contains("Generated by ArcLang from model") && text.contains("/* state_machine \""))?;
    let code = files.iter().find(|(name, _)| *name == header.0.replace(".h", ".c"))?;
    Some((header.0.clone(), header.1.clone(), code.0.clone(), code.1.clone()))
}

fn recovered(example: &str) -> (String, recover::Recovered, recover::Check) {
    let (header_name, header, code_name, code) = generated_c(example).expect("the example generates C");
    let generated = Generated { header_name: &header_name, header: &header, code_name: &code_name, code: &code };
    let model = recover::from_generated_c(&generated).expect("the C is read");
    let source = recover::to_arclang(&model, &generated);
    let check = recover::check(&source, &generated);
    (source, model, check)
}

#[test]
fn the_speed_monitor_is_recovered_from_its_c_and_generates_it_again() {
    let (source, model, check) = recovered("examples/automotive/speed-monitor/speed_monitor.arc");
    assert!(check.proven(), "{check:#?}\n{source}");
    assert_eq!(model.model, "SpeedMonitor");
    let names: Vec<&str> = model.machines.iter().map(|m| m.name.as_str()).collect();
    assert_eq!(names, ["Wheel speed filter", "Overspeed warning"]);
    // The block that only computes: its equations, no state.
    assert!(source.contains("\"filtered = filtered + 0.25 * (raw - filtered)\""), "{source}");
    // The machine: its states, where it starts, its guards, read in the code.
    let warning = &model.machines[1];
    assert_eq!(warning.states.iter().map(|s| s.path.as_str()).collect::<Vec<_>>(), ["Normal", "Warning"]);
    assert_eq!(warning.initial, Some(0));
    let guards: Vec<(usize, usize, Option<&str>)> = warning.transitions.iter().map(|t| (t.from, t.to, t.guard.as_deref())).collect();
    assert_eq!(guards, [(0, 1, Some("speed > on_above")), (1, 0, Some("speed < off_below"))]);
    // The input wired from the other machine.
    assert!(source.contains("in speed: Real [km/h] from \\\"Wheel speed filter\\\".speed"), "{source}");
}

#[test]
fn a_comment_that_lies_is_caught_by_the_check() {
    let (header_name, header, code_name, code) = generated_c("examples/automotive/speed-monitor/speed_monitor.arc").unwrap();
    // The comment says another equation than the statement under it computes.
    let lying = code.replace("/* filtered = filtered + 0.25 * (raw - filtered) */", "/* filtered = filtered + 0.5 * (raw - filtered) */");
    assert_ne!(lying, code);
    let generated = Generated { header_name: &header_name, header: &header, code_name: &code_name, code: &lying };
    let model = recover::from_generated_c(&generated).unwrap();
    let check = recover::check(&recover::to_arclang(&model, &generated), &generated);
    assert!(!check.proven());
    assert!(check.differences.iter().any(|d| d.read.contains("0.25 * (in->v_raw") && d.regenerated.contains("0.5 * (in->v_raw")), "{check:#?}");
}

#[test]
fn a_file_the_compiler_did_not_generate_is_refused() {
    let generated = Generated { header_name: "x.h", header: "#ifndef X_H\nint f(void);\n#endif\n", code_name: "x.c", code: "int f(void) { return 0; }\n" };
    let error = recover::from_generated_c(&generated).unwrap_err();
    assert!(error.contains("not a header the compiler generated"), "{error}");
}

/// How far the recovery goes on every example with machines; run with
/// `cargo test --test recover -- --ignored --nocapture`.
#[test]
#[ignore = "a survey, printed"]
fn survey() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let mut models: Vec<String> = Vec::new();
    let mut pending = vec![root.join("examples")];
    while let Some(dir) = pending.pop() {
        for entry in std::fs::read_dir(dir).unwrap().flatten() {
            let path = entry.path();
            if path.is_dir() {
                if !path.ends_with("archive") {
                    pending.push(path);
                }
            } else if path.extension().is_some_and(|e| e == "arc") {
                models.push(path.strip_prefix(root).unwrap().to_string_lossy().into_owned());
            }
        }
    }
    models.sort();
    let (mut with_c, mut proven) = (0, 0);
    for example in &models {
        let Some((header_name, header, code_name, code)) = generated_c(example) else { continue };
        with_c += 1;
        let generated = Generated { header_name: &header_name, header: &header, code_name: &code_name, code: &code };
        match recover::from_generated_c(&generated) {
            Err(error) => println!("UNREAD {example}: {error}"),
            Ok(model) => {
                let check = recover::check(&recover::to_arclang(&model, &generated), &generated);
                if check.proven() {
                    proven += 1;
                    println!("PROVEN {example}: {} machine(s)", model.machines.len());
                } else {
                    let first = check.error.clone().or_else(|| check.differences.first().map(|d| format!("{}:{} read `{}` regenerated `{}`", d.file, d.line, d.read, d.regenerated))).unwrap_or_default();
                    println!("DIFFER {example}: {} line(s); {}", check.differing_lines, first.chars().take(260).collect::<String>());
                }
            }
        }
    }
    println!("RECOVER {proven} of {with_c} examples with generated C are recovered and proven");
}

fn arclang(args: &[&str]) -> std::process::Output {
    std::process::Command::new(env!("CARGO_BIN_EXE_arclang")).args(args).output().expect("arclang runs")
}

#[test]
fn the_command_recovers_proves_and_says_what_it_does_not_cover() {
    let dir = tempfile::tempdir().unwrap();
    let root = Path::new(env!("CARGO_MANIFEST_DIR"));
    let text = |output: &std::process::Output| format!("{}{}", String::from_utf8_lossy(&output.stdout), String::from_utf8_lossy(&output.stderr));

    // A machine with guards and a block that computes: recovered and proven.
    let c = dir.path().join("sm");
    let model = root.join("examples/automotive/speed-monitor/speed_monitor.arc");
    assert!(arclang(&["export", model.to_str().unwrap(), "-f", "c", "-o", c.to_str().unwrap()]).status.success());
    let out = dir.path().join("recovered.arc");
    let proven = arclang(&["recover", c.to_str().unwrap(), "--check", "-o", out.to_str().unwrap()]);
    assert!(proven.status.success(), "{}", text(&proven));
    assert!(text(&proven).contains("Proven: the recovered model generates speed_monitor.h and speed_monitor.c as they were read"), "{}", text(&proven));
    // What is written is a model the compiler takes.
    assert!(arclang(&["check", out.to_str().unwrap()]).status.success());

    // Without --check, it says the recovery is not proven.
    let unproven = arclang(&["recover", c.join("speed_monitor.h").to_str().unwrap()]);
    assert!(unproven.status.success() && text(&unproven).contains("Not proven: `--check`"), "{}", text(&unproven));

    // A hand edit of the code that its comment does not follow fails the check, with the line.
    let code = c.join("speed_monitor.c");
    let edited = std::fs::read_to_string(&code).unwrap().replace("(in->v_speed > st->v_on_above)", "(in->v_speed >= st->v_on_above)");
    std::fs::write(&code, edited).unwrap();
    let drifted = arclang(&["recover", c.to_str().unwrap()]);
    assert!(text(&drifted).contains("guard: \"speed >= on_above\""), "the guard is read in the code: {}", text(&drifted));

    // A machine with regions: recovered as far as the reader goes, and not called proven.
    let c = dir.path().join("charger");
    let model = root.join("examples/energy/battery-charger/battery_charger.arc");
    assert!(arclang(&["export", model.to_str().unwrap(), "-f", "c", "-o", c.to_str().unwrap()]).status.success());
    let regions = arclang(&["recover", c.to_str().unwrap(), "--check", "-o", dir.path().join("charger.arc").to_str().unwrap()]);
    assert!(!regions.status.success(), "{}", text(&regions));
    assert!(text(&regions).contains("it has regions, which this reader does not recover yet") && text(&regions).contains("Not proven"), "{}", text(&regions));

    // A directory with no generated C.
    let nothing = arclang(&["recover", dir.path().to_str().unwrap()]);
    assert!(!nothing.status.success() && text(&nothing).contains("holds no header the compiler generated"), "{}", text(&nothing));
}
