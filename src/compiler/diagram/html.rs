//! HTML packaging of the diagram viewer.
//!
//! The viewer is three assets under `viewer/`: the pure SVG renderer, the
//! interactive shell and its stylesheet, plus the ELK layout engine. This
//! module bundles them with a model's diagrams, either as a standalone page
//! ([`standalone_html`]) or as parts to splice into another document
//! ([`viewer_parts`], used by the architecture explorer).
//!
//! Native builds inline the layout engine so the output works offline. Other
//! targets (WebAssembly) reference the identical file on a CDN, pinned by a
//! subresource-integrity hash, rather than carrying 1.6 MB in the module.

use super::{elk, DiagramSet};
use serde_json::json;

/// Version of the vendored layout engine (`viewer/vendor/elk.bundled.js`).
pub const ELK_VERSION: &str = "0.9.3";
/// Subresource-integrity hash of that file; `html_tests` checks it matches.
pub const ELK_INTEGRITY: &str =
    "sha384-KO35c6PFq7tFxAEx6FtATwL9vOBOmCzQYr7GM0iTr3oO22s7Jc9OkclOH4AV7jwK";

const RENDER_JS: &str = include_str!("viewer/arcviz-render.js");
const LINKS_JS: &str = include_str!("viewer/arcviz-links.js");
const NAVIGATION_JS: &str = include_str!("viewer/arcviz-navigation.js");
const COLLAPSE_JS: &str = include_str!("viewer/arcviz-collapse.js");
const SCOPE_JS: &str = include_str!("viewer/arcviz-scope.js");
const EXPORT_JS: &str = include_str!("viewer/arcviz-export.js");
const STAGE_JS: &str = include_str!("viewer/arcviz-stage.js");
const PLACE_JS: &str = include_str!("viewer/arcviz-place.js");
const VIEWER_JS: &str = include_str!("viewer/arcviz-viewer.js");
const VIEWER_CSS: &str = include_str!("viewer/arcviz-viewer.css");
#[cfg(feature = "native")]
const ELK_JS: &str = include_str!("viewer/vendor/elk.bundled.js");

/// Id of the element the viewer mounts into.
pub const HOST_ID: &str = "arcviz-viewer";

/// The viewer, ready to splice into a host document.
pub struct ViewerParts {
    /// A `<style>` element; belongs in `<head>`.
    pub style: String,
    /// The mount point, the embedded diagram data and the scripts; belongs
    /// where the diagrams should appear.
    pub body: String,
}

/// Build the viewer for a model's diagrams. `title` names the model in
/// exported file names.
pub fn viewer_parts(set: &DiagramSet, title: &str) -> ViewerParts {
    let payload = json!({
        "title": title,
        "graphs": set.diagrams.iter().map(elk::to_elk).collect::<Vec<_>>(),
        "diagnostics": set.diagnostics,
        "links": set.links,
        "layout": set.layout,
        "layout_name": set.layout_name,
    });
    let body = format!(
        "<div id=\"{HOST_ID}\"></div>\n\
         <script type=\"application/json\" id=\"arcviz-data\">{data}</script>\n\
         {engine}\n\
         <script>{render}</script>\n\
         <script>{links}</script>\n\
         <script>{navigation}</script>\n\
         <script>{collapse}</script>\n\
         <script>{scope}</script>\n\
         <script>{export}</script>\n\
         <script>{stage}</script>\n\
         <script>{place}</script>\n\
         <script>{viewer}</script>\n\
         <script>window.arcvizViewer = ArcViz.mount(\
         document.getElementById('{HOST_ID}'), \
         JSON.parse(document.getElementById('arcviz-data').textContent), \
         {{ ELK: ELK, render: ArcVizRender, links: ArcVizLinks, \
         navigation: ArcVizNavigation, collapse: ArcVizCollapse, \
         scope: ArcVizScope, exporter: ArcVizExport, stage: ArcVizStage, \
         place: ArcVizPlace }});</script>",
        data = json_for_script(&payload),
        engine = engine_script(),
        render = inline_script(RENDER_JS),
        links = inline_script(LINKS_JS),
        navigation = inline_script(NAVIGATION_JS),
        collapse = inline_script(COLLAPSE_JS),
        scope = inline_script(SCOPE_JS),
        export = inline_script(EXPORT_JS),
        stage = inline_script(STAGE_JS),
        place = inline_script(PLACE_JS),
        viewer = inline_script(VIEWER_JS),
    );
    ViewerParts {
        style: format!("<style>{VIEWER_CSS}</style>"),
        body,
    }
}

/// A complete, self-contained HTML page showing a model's diagrams.
pub fn standalone_html(set: &DiagramSet, title: &str) -> String {
    let parts = viewer_parts(set, title);
    format!(
        "<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n\
         <meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n\
         <meta name=\"generator\" content=\"ArcLang {version}\">\n\
         <title>{title} — architecture diagrams</title>\n\
         <style>{page_css}</style>\n{style}\n</head>\n<body>\n\
         <header class=\"page-head\"><h1>{title}</h1><p>Architecture diagrams</p></header>\n\
         <main>\n{body}\n</main>\n\
         <footer class=\"page-foot\">Generated by ArcLang {version}. Layout by ELK {elk}.</footer>\n\
         </body>\n</html>\n",
        version = env!("CARGO_PKG_VERSION"),
        title = escape_html(title),
        page_css = PAGE_CSS,
        style = parts.style,
        body = parts.body,
        elk = ELK_VERSION,
    )
}

