#[cfg(feature = "native")]
fn engine_script() -> String {
    format!("<script>{}</script>", inline_script(ELK_JS))
}

#[cfg(not(feature = "native"))]
fn engine_script() -> String {
    format!(
        "<script src=\"https://unpkg.com/elkjs@{ELK_VERSION}/lib/elk.bundled.js\" \
         integrity=\"{ELK_INTEGRITY}\" crossorigin=\"anonymous\"></script>"
    )
}

/// JavaScript made safe to inline: a `</script` inside it would end the
/// element early. `<\/script` is the same token to the JavaScript parser.
fn inline_script(source: &str) -> String {
    source
        .replace("</script", "<\\/script")
        .replace("</SCRIPT", "<\\/SCRIPT")
}

/// JSON made safe inside a `<script type="application/json">` element: no
/// `<` survives, so model text can neither close the element nor open a
/// comment. `<` parses back to `<`.
fn json_for_script(value: &serde_json::Value) -> String {
    value.to_string().replace('<', "\\u003c")
}

fn escape_html(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::compiler::diagram::build_diagrams;
    use crate::compiler::{Compiler, CompilerConfig};

    fn set_of(source: &str) -> DiagramSet {
        let result = Compiler::new(CompilerConfig::default())
            .compile_string(source)
            .expect("compiles");
        build_diagrams(&result.ast)
    }

    #[test]
    fn model_text_cannot_break_out_of_the_data_element() {
        let set = set_of(
            r#"
logical_architecture LA {
  component Evil {
    description: "</script><script>alert(1)</script><!--"
  }
}
"#,
        );
        let parts = viewer_parts(&set, "</script><b>");

        let start = parts
            .body
            .find("id=\"arcviz-data\">")
            .expect("data element")
            + "id=\"arcviz-data\">".len();
        let end = start
            + parts.body[start..]
                .find("</script>")
                .expect("data element closes");
        let data = &parts.body[start..end];
        assert!(!data.contains('<'), "raw '<' in embedded JSON");
        let parsed: serde_json::Value = serde_json::from_str(data).expect("still valid JSON");
        assert_eq!(parsed["title"], "</script><b>");
        assert_eq!(
            parsed["graphs"][0]["children"][0]["arc"]["properties"]["description"],
            "</script><script>alert(1)</script><!--"
        );
    }

    #[test]
    fn standalone_page_escapes_the_title_and_mounts_the_viewer() {
        let set =
            set_of("logical_architecture LA {\n  component C {\n    description: \"c\"\n  }\n}\n");
        let html = standalone_html(&set, "A <b> & C");

        assert!(html.contains("<title>A &lt;b&gt; &amp; C — architecture diagrams</title>"));
        assert!(html.contains("<div id=\"arcviz-viewer\"></div>"));
        assert!(html.contains("ArcViz.mount("));
        assert!(html.starts_with("<!DOCTYPE html>"));
    }

    #[test]
    fn inlined_scripts_contain_no_closing_script_tag() {
        for source in [RENDER_JS, LINKS_JS, NAVIGATION_JS, COLLAPSE_JS, SCOPE_JS, EXPORT_JS, STAGE_JS, PLACE_JS, VIEWER_JS] {
            assert!(!inline_script(source).to_lowercase().contains("</script"));
        }
    }

    #[cfg(feature = "native")]
    #[test]
    fn native_output_is_self_contained() {
        let set =
            set_of("logical_architecture LA {\n  component C {\n    description: \"c\"\n  }\n}\n");
        let html = standalone_html(&set, "Offline");

        assert!(!html.contains("src=\"http"), "no script may be fetched");
        assert!(
            !html.contains("href=\"http"),
            "no stylesheet may be fetched"
        );
        assert!(!inline_script(ELK_JS).to_lowercase().contains("</script"));
    }

    #[cfg(feature = "native")]
    #[test]
    fn integrity_hash_matches_the_vendored_engine() {
        use sha2::Digest;
        const ALPHABET: &[u8; 64] =
            b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
        let digest = sha2::Sha384::digest(ELK_JS.as_bytes());
        // SHA-384 is 48 bytes: a whole number of 3-byte groups, no padding.
        let encoded: String = digest
            .chunks(3)
            .flat_map(|group| {
                let bits =
                    (u32::from(group[0]) << 16) | (u32::from(group[1]) << 8) | u32::from(group[2]);
                [18, 12, 6, 0].map(|shift| char::from(ALPHABET[((bits >> shift) & 63) as usize]))
            })
            .collect();
        assert_eq!(ELK_INTEGRITY, format!("sha384-{encoded}"));
    }
}
