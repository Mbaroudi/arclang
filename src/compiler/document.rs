    #[test]
    fn markdown_reads_as_blocks() {
        let found = blocks("# Title\n\nA **bold** line\nthat goes on.\n\n- one\n- two\n\n| A | B |\n|---|---|\n| 1 | x \\| y |\n\n```\ncode\n```\n");
        assert_eq!(
            found,
            [
                Block::Heading(1, "Title".into()),
                Block::Paragraph("A **bold** line that goes on.".into()),
                Block::Bullet("one".into()),
                Block::Bullet("two".into()),
                Block::Table(vec![vec!["A".into(), "B".into()], vec!["1".into(), "x | y".into()]]),
                Block::Code("code".into()),
            ]
        );
    }

    #[test]
    fn a_directive_splits_into_words_and_quoted_text() {
        assert_eq!(words("elements PhysicalNode where \"mass > 10 kg\" columns mass, voltage").unwrap(), ["elements", "PhysicalNode", "where", "mass > 10 kg", "columns", "mass", "voltage"]);
        assert!(words("value \"PN-1").is_err());
    }
