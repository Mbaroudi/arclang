//! The I/O channels of the SoC, for the cases that run through a binding:
//! the Zephyr devicetree nodes of its peripherals (from the SoC's map), the
//! hook that tells the simulated bench where the cycles end, the stimulus
//! the bench plays (`player.hex`) and the channels it records
//! (`recorder.txt`), read back as the Renode bench reports them.
//!
//! The channels are those of the target zephyr/litex_vexriscv: gpio 0 to
//! 31 in and out, pwm 0 and 1, uart 0 and 1 beside the console, adc 0 to 7
//! (a register bank), the watchdog. CAN is not in the SoC yet: a case that
//! needs it runs in Renode (`arclang pil`).

use super::super::binding::{Binding, Sink};
use std::fmt::Write as _;

/// The alias each channel of `arclang_io_zephyr.c` is found by, and the node.
const ALIASES: &[(&str, &str)] = &[
    ("arclang-gpio-in", "gpio_in"),
    ("arclang-gpio-out", "gpio_out"),
    ("arclang-pwm-0", "pwm0"),
    ("arclang-pwm-1", "arclang_pwm1"),
    ("arclang-uart-0", "arclang_uart0"),
    ("arclang-uart-1", "arclang_uart1"),
    ("arclang-adc", "arclang_adc"),
];

/// The value the application writes to the bench's register when its I/O is up.
pub const IO_UP: u32 = 0xFFFF_FFFF;

fn register(csr: &serde_json::Value, name: &str) -> Result<u64, String> {
    csr["csr_registers"][name]["addr"].as_u64().ok_or_else(|| format!("the SoC's map has no register {name}"))
}

fn irq(csr: &serde_json::Value, name: &str) -> Result<u64, String> {
    csr["constants"][format!("{name}_interrupt")].as_u64().ok_or_else(|| format!("the SoC's map has no interrupt for {name}"))
}

/// `reg = <a 0x4>, ...; reg-names = "...", ...;` for a core's registers.
fn regs(csr: &serde_json::Value, core: &str, names: &[&str], indent: &str) -> Result<String, String> {
    let mut addrs = Vec::new();
    for n in names {
        addrs.push(format!("<0x{:08x} 0x4>", register(csr, &format!("{core}_{n}"))?));
    }
    Ok(format!(
        "{indent}reg = {};\n{indent}reg-names = {};\n",
        addrs.join(",\n").replace('\n', &format!("\n{indent}      ")),
        names.iter().map(|n| format!("\"{n}\"")).collect::<Vec<_>>().join(", ")
    ))
}

const UART_REGS: &[&str] = &["rxtx", "txfull", "rxempty", "ev_status", "ev_pending", "ev_enable", "txempty", "rxfull"];
const PWM_REGS: &[&str] = &["enable", "width", "period"];

/// The devicetree of the SoC's channels, from its map (`csr.json`).
pub fn overlay(csr: &serde_json::Value) -> Result<String, String> {
    let mut out = String::from("\n/* ArcLang: the channels of the SoC (arclang_io_zephyr.c finds them by their aliases). */\n");
    let _ = write!(out, "&gpio_in {{\n{}    interrupts = <{} 2>;\n    ngpios = <32>;\n    status = \"okay\";\n}};\n", regs(csr, "gpio_in", &["in", "mode", "edge", "ev_pending", "ev_enable"], "    ")?, irq(csr, "gpio_in")?);
    let _ = write!(out, "&gpio_out {{\n{}    ngpios = <32>;\n    status = \"okay\";\n}};\n", regs(csr, "gpio_out", &["out"], "    ")?);
    let _ = write!(out, "&pwm0 {{\n{}    status = \"okay\";\n}};\n", regs(csr, "pwm0", PWM_REGS, "    ")?);
    out.push_str("/ {\n    aliases {\n");
    for (alias, node) in ALIASES {
        let _ = writeln!(out, "        {alias} = &{node};");
    }
    out.push_str("    };\n    soc {\n");
    let pwm1 = register(csr, "pwm1_enable")?;
    let _ = write!(out, "        arclang_pwm1: pwm@{pwm1:x} {{\n            compatible = \"litex,pwm\";\n{}            #pwm-cells = <2>;\n            status = \"okay\";\n        }};\n", regs(csr, "pwm1", PWM_REGS, "            ")?);
    for k in 0..2 {
        let core = format!("uart_a{k}");
        let base = register(csr, &format!("{core}_rxtx"))?;
        let _ = write!(
            out,
            "        arclang_uart{k}: serial@{base:x} {{\n            compatible = \"litex,uart\";\n            interrupt-parent = <&intc0>;\n            interrupts = <{} 10>;\n{}            current-speed = <115200>;\n            status = \"okay\";\n        }};\n",
            irq(csr, &core)?,
            regs(csr, &core, UART_REGS, "            ")?
        );
    }
    let adc = register(csr, "adc_ch0")?;
    let _ = write!(out, "        arclang_adc: adc@{adc:x} {{\n            compatible = \"arclang,litex-adc\";\n            reg = <0x{adc:08x} 0x20>;\n            channels = <8>;\n            #io-channel-cells = <1>;\n            status = \"okay\";\n        }};\n");
    out.push_str("    };\n};\n");
    Ok(out)
}

/// The hook of the PIL application (`arclang_pil_bench` in pil_io.c): the
/// event written to the bench's register.
pub fn hook(csr: &serde_json::Value) -> Result<String, String> {
    let addr = register(csr, "bench_cycle")?;
    Ok(format!(
        "/* Generated by ArcLang (arclang soc): the PIL application tells the SoC's\n   bench register its events (the I/O up, then the end of each cycle). */\n#include <stdint.h>\n\nvoid arclang_pil_bench(uint32_t event)\n{{\n    *(volatile uint32_t *)0x{addr:08X}UL = event;\n}}\n"
    ))
}

/// The stimulus: per step, its operations (`g pin level`, `a channel raw`,
/// `u port byte`) as two words each, then the end of the step.
pub fn player(steps: &[Vec<String>]) -> Result<String, String> {
    let mut words: Vec<u32> = Vec::new();
    for (k, ops) in steps.iter().enumerate() {
        for op in ops {
            let fields: Vec<&str> = op.split_whitespace().collect();
            let number = |i: usize| -> Result<u32, String> {
                let t = fields.get(i).ok_or_else(|| format!("operation '{op}' is short"))?;
                let parsed = match t.strip_prefix("0x") {
                    Some(hex) => u32::from_str_radix(hex, 16),
                    None => t.parse::<u32>(),
                };
                parsed.map_err(|_| format!("operation '{op}': '{t}' is no number"))
            };
            let code = match fields.first().copied() {
                Some("g") => 1,
                Some("a") => 2,
                Some("u") => 3,
                Some("c") => return Err(format!("step {k}: a CAN frame; the SoC has no CAN core yet: run this case in Renode (arclang pil)")),
                _ => return Err(format!("step {k}: operation '{op}' is not one the SoC's bench plays")),
            };
            let (a, b) = (number(1)?, number(2)?);
            let limit = match code {
                1 => 31,
                2 => 7,
                _ => 1,
            };
            if a > limit {
                return Err(format!("step {k}: '{op}': the SoC has {} of these channels", limit + 1));
            }
            words.push((code << 24) | a);
            words.push(b);
        }
        words.push(0xFE00_0000);
    }
    words.push(0xFF00_0000);
    Ok(words.iter().map(|w| format!("{w:08x}\n")).collect())
}

/// The channels after each cycle, read from the recorder as the binding's
/// outputs and its watchdog: one line `v1,v2...` a step.
pub fn outputs(binding: &Binding, recorder: &str, steps: usize) -> Result<Vec<String>, String> {
    let mut base_feeds: Option<u64> = None;
    let mut snapshots: Vec<Vec<u64>> = Vec::new();
    let mut sent: Vec<(usize, u64, u64)> = Vec::new();
    for line in recorder.lines() {
        let f: Vec<u64> = line.split_whitespace().skip(1).map(|t| t.parse::<u64>().unwrap_or(0)).collect();
        match line.split_whitespace().next() {
            Some("B") => base_feeds = f.first().copied(),
            Some("S") if f.len() == 9 => snapshots.push(f),
            Some("T") if f.len() == 3 => sent.push((f[0] as usize, f[1], f[2])),
            _ => {}
        }
    }
    let base = base_feeds.ok_or("the bench saw no start of the I/O (the application never said its I/O was up)")?;
    if snapshots.len() < steps {
        return Err(format!("the bench recorded {} of {steps} cycles", snapshots.len()));
    }
    let permille = |enable: u64, width: u64, period: u64| if enable == 0 || period == 0 { 0 } else { width * 1000 / period };
    let mut rows = Vec::new();
    for (k, s) in snapshots.iter().take(steps).enumerate() {
        let mut values: Vec<String> = Vec::new();
        for o in &binding.outputs {
            let v = match o.sink {
                Sink::Gpio(p) => (s[1] >> p) & 1,
                Sink::Pwm(0, _) => permille(s[2], s[3], s[4]),
                Sink::Pwm(1, _) => permille(s[5], s[6], s[7]),
                Sink::Uart(p, byte) if p < 2 => sent.iter().filter(|(step, port, b)| *step == k && *port == p as u64 && *b == byte as u64).count() as u64,
                other => return Err(format!("output {other:?}: not a channel of the SoC yet")),
            };
            values.push(v.to_string());
        }
        if binding.watchdog {
            values.push(s[8].saturating_sub(base).to_string());
        }
        rows.push(values.join(","));
    }
    Ok(rows)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_stimulus_is_two_words_an_operation_and_can_is_refused() {
        let hex = player(&[vec!["g 3 1".into(), "u 0 0x52".into()], vec![], vec!["a 1 3000".into()]]).unwrap();
        assert_eq!(hex, "01000003\n00000001\n03000000\n00000052\nfe000000\nfe000000\n02000001\n00000bb8\nfe000000\nff000000\n");
        assert!(player(&[vec!["c 0x210 1".into()]]).unwrap_err().contains("no CAN core yet"));
        assert!(player(&[vec!["g 40 1".into()]]).unwrap_err().contains("32 of these channels"));
    }
}
