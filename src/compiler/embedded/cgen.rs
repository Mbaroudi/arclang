//! Portable C99 from the state machines of a model: `<model>.h` and
//! `<model>.c`, an `init()` / `step()` API over structures the caller owns.
//!
//! The code knows no board: no `malloc`, no OS call, no global variable
//! (the only file-scope objects are `static const` tables), loops bounded by
//! the size of the machine, no recursion. A step reads the inputs, fires
//! what they enable as `execution::Machine` does, counts the actions run
//! and reports the states active; it never touches a register.

use super::cexpr::{self, Access, Helpers};
use super::plan::{Guard, Kind, MachinePlan, Plan, Trigger};
use crate::compiler::execution::expr::{BlockKind, Direction};
use std::fmt::Write as _;

/// The generated files: (name, text).
#[derive(Debug, Clone)]
pub struct Generated {
    pub header_name: String,
    pub header: String,
    pub source_name: String,
    pub source: String,
}

/// Text for a C comment: no `*/`, no line break.
pub fn comment(text: &str) -> String {
    text.replace("*/", "* /").replace(['\n', '\r'], " ")
}

pub fn period_macro(plan: &Plan) -> String {
    format!("{}_PERIOD_US", plan.ident.to_uppercase())
}

fn type_prefix(plan: &Plan, machine: &MachinePlan) -> String {
    format!("{}_{}", plan.ident, machine.ident)
}

fn pid_type(plan: &Plan) -> String {
    format!("{}_pid_state", plan.ident)
}

fn banner(plan: &Plan, what: &str) -> String {
    format!(
        "/*\n * {what}\n * Generated by ArcLang from model \"{}\". Do not edit: regenerate.\n * Portable C99: no dynamic memory, no OS call, no hidden state; the\n * caller owns every structure. See docs/embedded-c.md.\n */\n",
        comment(&plan.model)
    )
}

pub fn generate(plan: &Plan, default_period_us: u64) -> Generated {
    Generated {
        header_name: format!("{}.h", plan.ident),
        header: header(plan, default_period_us),
        source_name: format!("{}.c", plan.ident),
        source: source(plan),
    }
}

fn header(plan: &Plan, default_period_us: u64) -> String {
    let guard = format!("ARCLANG_{}_H", plan.ident.to_uppercase());
    let period = period_macro(plan);
    let mut out = banner(plan, "The behavior of the model: its state machines.");
    let _ = writeln!(out, "#ifndef {guard}\n#define {guard}\n\n#include <stdbool.h>\n#include <stdint.h>\n\n#ifdef __cplusplus\nextern \"C\" {{\n#endif\n");
    if plan.machines.iter().any(|m| super::cexpr::uses_pid(m.program())) {
        let _ = writeln!(out, "/* The state of a PID block. */\ntypedef struct {{\n    double integral;\n    double previous;\n    bool primed;\n}} {};\n", pid_type(plan));
    }
    let _ = writeln!(out, "/* The step period, in microseconds: timed transitions count steps of it. */\n#ifndef {period}\n#define {period} {default_period_us}UL\n#endif\n#if {period} == 0\n#error \"{period} must be positive\"\n#endif\n");
    for m in &plan.machines {
        let t = type_prefix(plan, m);
        let _ = writeln!(out, "/* state_machine \"{}\" */", comment(&m.name));
        let _ = writeln!(out, "#define {}_STATE_COUNT {}U\n", t.to_uppercase(), m.states.len());
        let _ = writeln!(out, "typedef struct {{");
        for e in &m.events {
            let _ = writeln!(out, "    bool {}; /* event \"{}\": true in the step it occurs */", e.ident, comment(&e.text));
        }
        for c in &m.conditions {
            let _ = writeln!(out, "    bool {}; /* condition \"{}\": whether it holds in the step */", c.ident, comment(&c.text));
        }
        let program = m.program();
        let unit = |v: &crate::compiler::execution::expr::Variable| v.unit.as_ref().map(|u| format!(" [{u}]")).unwrap_or_default();
        for (i, v) in program.inputs() {
            let _ = writeln!(out, "    {} {}; /* in variable \"{}\"{}: its value in the step */", v.ty.c(), m.variables[i].ident, comment(&v.name), comment(&unit(v)));
        }
        if m.events.is_empty() && m.conditions.is_empty() && program.inputs().next().is_none() {
            let _ = writeln!(out, "    uint8_t unused_; /* the machine reads no input */");
        }
        let _ = writeln!(out, "}} {t}_inputs;\n");
        let _ = writeln!(out, "typedef struct {{");
        for s in &m.states {
            let _ = writeln!(out, "    bool {}; /* state {}: active after the step */", s.ident, comment(&s.path));
        }
        for a in &m.actions {
            let _ = writeln!(out, "    uint8_t {}; /* action \"{}\": times run in the step (saturates at 255) */", a.ident, comment(&a.text));
        }
        for (i, v) in program.variables.iter().enumerate() {
            let _ = writeln!(out, "    {} {}; /* variable \"{}\"{}: its value after the step */", v.ty.c(), m.variables[i].ident, comment(&v.name), comment(&unit(v)));
        }
        let _ = writeln!(out, "}} {t}_outputs;\n");
        let _ = writeln!(out, "typedef struct {{\n    bool active[{n}];\n    uint32_t in_state[{n}]; /* steps since the state was entered (saturates) */", n = m.states.len());
        for (i, v) in program.variables.iter().enumerate().filter(|(_, v)| v.direction != crate::compiler::execution::expr::Direction::In) {
            let _ = writeln!(out, "    {} {}; /* variable \"{}\"{} */", v.ty.c(), m.variables[i].ident, comment(&v.name), comment(&unit(v)));
        }
        for b in 0..program.blocks.len() {
            let _ = writeln!(out, "    {} blk_{b}; /* the state of a block of the equations */", super::cexpr::block_field(program, b, &pid_type(plan)));
        }
        let _ = writeln!(out, "}} {t}_state;\n");
    }
    let p = &plan.ident;
    for (kind, name) in [("inputs", "inputs"), ("outputs", "outputs")] {
        let _ = writeln!(out, "typedef struct {{");
        for m in &plan.machines {
            let _ = writeln!(out, "    {}_{kind} {};", type_prefix(plan, m), m.ident);
        }
        let _ = writeln!(out, "}} {p}_{name};\n");
    }
    let _ = writeln!(out, "typedef struct {{\n    bool started;");
    for m in &plan.machines {
        let _ = writeln!(out, "    {}_state {};", type_prefix(plan, m), m.ident);
    }
    let _ = writeln!(out, "}} {p}_state;\n");
    let _ = writeln!(
        out,
        "/* Reset the state: no state is active until the first step, which enters\n   the initial states (their entry actions count in that step). */\nvoid {p}_init({p}_state *state);\n\n/* One step: the initial states on the first one; then, in each machine, the\n   events as declared, the timed transitions, the completion transitions; the\n   do activities of the active states; the outputs. */\nvoid {p}_step({p}_state *state, const {p}_inputs *inputs, {p}_outputs *outputs);\n"
    );
    let _ = writeln!(out, "#ifdef __cplusplus\n}}\n#endif\n\n#endif /* {guard} */");
    out
}

fn guard_expr(m: &MachinePlan, guard: &Guard, access: &Access, h: &mut Helpers) -> Option<String> {
    match guard {
        Guard::Always => Some(String::new()),
        Guard::Never => None,
        Guard::Condition(i) => Some(format!(" && in->{}", m.conditions[*i].ident)),
        Guard::Code(text) => Some(format!(" && {}", access.expr(&m.program().guards[text], h))),
    }
}

/// The code of an action, when it is code, as lines at `indent`.
fn action_code(m: &MachinePlan, action: usize, indent: &str, access: &Access, h: &mut Helpers, out: &mut String) {
    if let Some(code) = m.program().actions.get(m.actions[action].text.trim()) {
        access.statements(code, indent, h, out);
    }
}

fn source(plan: &Plan) -> String {
    let mut h = Helpers::default();
    let mut body = String::new();
    for m in &plan.machines {
        machine_source(plan, m, &mut h, &mut body);
    }
    let p = &plan.ident;
    let _ = writeln!(body, "void {p}_init({p}_state *state)\n{{\n    uint16_t k;\n    state->started = false;");
    for m in &plan.machines {
        let i = &m.ident;
        let _ = writeln!(body, "    for (k = 0U; k < {n}U; k++) {{\n        state->{i}.active[k] = false;\n        state->{i}.in_state[k] = 0U;\n    }}", n = m.states.len());
        let program = m.program();
        for (n, v) in program.variables.iter().enumerate().filter(|(_, v)| v.direction != Direction::In) {
            let _ = writeln!(body, "    state->{i}.{} = {};", m.variables[n].ident, cexpr::constant(v.initial));
        }
        for (b, block) in program.blocks.iter().enumerate() {
            match block.kind {
                BlockKind::Delay => {
                    let _ = writeln!(body, "    state->{i}.blk_{b} = {};", cexpr::constant(block.initial));
                }
                BlockKind::Integrator { .. } => {
                    let _ = writeln!(body, "    state->{i}.blk_{b} = 0.0;");
                }
                BlockKind::Pid { .. } => {
                    let _ = writeln!(body, "    state->{i}.blk_{b}.integral = 0.0;\n    state->{i}.blk_{b}.previous = 0.0;\n    state->{i}.blk_{b}.primed = false;");
                }
            }
        }
    }
    let _ = writeln!(body, "}}\n");
    let _ = writeln!(body, "void {p}_step({p}_state *state, const {p}_inputs *inputs, {p}_outputs *outputs)\n{{\n    bool starting = !state->started;\n    state->started = true;");
    for m in &plan.machines {
        let i = &m.ident;
        for a in &m.actions {
            let _ = writeln!(body, "    outputs->{i}.{} = 0U;", a.ident);
        }
        let _ = writeln!(body, "    if (starting) {{");
        for &top in &m.machine.tops {
            let _ = writeln!(body, "        {i}_enter(&state->{i}, &inputs->{i}, &outputs->{i}, {top}U); /* {} */", comment(&m.states[top].path));
        }
        let _ = writeln!(body, "    }}\n    {i}_run(&state->{i}, &inputs->{i}, &outputs->{i});");
        for (n, s) in m.states.iter().enumerate() {
            let _ = writeln!(body, "    outputs->{i}.{} = state->{i}.active[{n}];", s.ident);
        }
        for (n, v) in m.program().variables.iter().enumerate() {
            let from = if v.direction == Direction::In { "inputs" } else { "state" };
            let _ = writeln!(body, "    outputs->{i}.{f} = {from}->{i}.{f};", f = m.variables[n].ident);
        }
    }
    let _ = writeln!(body, "}}");

    let mut out = banner(plan, "The behavior of the model: its state machines.");
    let _ = writeln!(out, "#include \"{}.h\"\n", plan.ident);
    if plan.machines.iter().any(|m| !m.program().is_empty()) {
        let _ = writeln!(out, "/* The arithmetic is the model's: no contraction of a * b + c into one rounding. */\n#if defined(__clang__)\n#pragma STDC FP_CONTRACT OFF\n#endif\n");
    }
    let _ = writeln!(out, "#define NO_STATE 0xFFFFU\n");
    let any_action = plan.machines.iter().any(|m| !m.actions.is_empty());
    if any_action {
        let _ = writeln!(out, "static uint8_t counted(uint8_t n)\n{{\n    return (n < 255U) ? (uint8_t)(n + 1U) : n;\n}}\n");
    }
    out.push_str(&cexpr::definitions(&h, &pid_type(plan)));
    out.push_str(&body);
    out
}

fn machine_source(plan: &Plan, m: &MachinePlan, h: &mut Helpers, out: &mut String) {
    let t = type_prefix(plan, m);
    let i = &m.ident;
    let n = m.states.len();
    let depth = m.max_depth;
    let st = format!("{t}_state");
    let inp = format!("{t}_inputs");
    let o = format!("{t}_outputs");
    let period = period_macro(plan);
    let access = Access { machine: m, state: "st", inputs: "in", period: &period };
    let _ = writeln!(out, "/* ---- state_machine \"{}\" ---- */\n", comment(&m.name));
    let _ = writeln!(out, "/* States, by index:");
    for (k, s) in m.states.iter().enumerate() {
        let _ = writeln!(out, "     {k}: {}", comment(&s.path));
    }
    let _ = writeln!(out, "*/");
    for note in &m.notes {
        let _ = writeln!(out, "/* note: {} */", comment(note));
    }
    let list = |values: Vec<String>| values.join(", ");
    let index = |v: Option<usize>| v.map(|x| format!("{x}U")).unwrap_or_else(|| "NO_STATE".to_string());
    let has_transitions = !m.transitions.is_empty();
    if has_transitions {
        let _ = writeln!(out, "static const uint16_t {i}_parent[{n}] = {{ {} }};", list(m.states.iter().map(|s| index(s.parent)).collect()));
    }
    let _ = writeln!(out, "static const uint16_t {i}_initial[{n}] = {{ {} }};\n", list(m.states.iter().map(|s| index(s.initial)).collect()));
    let actions_fn = |name: &str, pick: &dyn Fn(&super::plan::StatePlan) -> &Vec<usize>, out: &mut String, h: &mut Helpers| {
        let _ = writeln!(out, "static void {i}_{name}({st} *st, const {inp} *in, {o} *out, uint16_t s)\n{{");
        let cases: Vec<(usize, &Vec<usize>)> = m.states.iter().enumerate().map(|(k, s)| (k, pick(s))).filter(|(_, a)| !a.is_empty()).collect();
        let _ = writeln!(out, "    (void)st;\n    (void)in;");
        if cases.is_empty() {
            let _ = writeln!(out, "    (void)s;\n    (void)out;");
        } else {
            let _ = writeln!(out, "    switch (s) {{");
            for (k, acts) in cases {
                let _ = writeln!(out, "    case {k}U: /* {} */", comment(&m.states[k].path));
                for a in acts {
                    let id = &m.actions[*a].ident;
                    let _ = writeln!(out, "        out->{id} = counted(out->{id});");
                    action_code(m, *a, "        ", &access, h, out);
                }
                let _ = writeln!(out, "        break;");
            }
            let _ = writeln!(out, "    default:\n        break;\n    }}");
        }
        let _ = writeln!(out, "}}\n");
    };
    actions_fn("entry_actions", &|s| &s.entry, out, h);
    let _ = writeln!(out, "static void {i}_enter_one({st} *st, const {inp} *in, {o} *out, uint16_t s)\n{{\n    st->active[s] = true;\n    st->in_state[s] = 0U;\n    {i}_entry_actions(st, in, out, s);\n}}\n");
    let _ = writeln!(
        out,
        "/* Enter s and the initial states under it, down to a leaf. */\nstatic void {i}_enter({st} *st, const {inp} *in, {o} *out, uint16_t s)\n{{\n    uint16_t current = s;\n    uint16_t level;\n    for (level = 0U; level < {depth}U; level++) {{\n        {i}_enter_one(st, in, out, current);\n        if ({i}_initial[current] == NO_STATE) {{\n            break;\n        }}\n        current = {i}_initial[current];\n    }}\n}}\n"
    );
    if has_transitions {
        actions_fn("exit_actions", &|s| &s.exit, out, h);
        let _ = writeln!(
            out,
            "/* Exit s and the active states under it, deepest first. */\nstatic void {i}_exit({st} *st, const {inp} *in, {o} *out, uint16_t s)\n{{\n    uint16_t leaf = s;\n    uint16_t level;\n    uint16_t k;\n    bool deeper;\n    for (level = 0U; level < {depth}U; level++) {{\n        deeper = false;\n        for (k = 0U; k < {n}U; k++) {{\n            if (({i}_parent[k] == leaf) && st->active[k]) {{\n                leaf = k;\n                deeper = true;\n                break;\n            }}\n        }}\n        if (!deeper) {{\n            break;\n        }}\n    }}\n    for (level = 0U; level < {depth}U; level++) {{\n        if (st->active[leaf]) {{\n            st->active[leaf] = false;\n            {i}_exit_actions(st, in, out, leaf);\n        }}\n        if ((leaf == s) || ({i}_parent[leaf] == NO_STATE)) {{\n            break;\n        }}\n        leaf = {i}_parent[leaf];\n    }}\n}}\n"
        );
    }
    for (k, tr) in m.transitions.iter().enumerate() {
        if tr.guard == Guard::Never {
            continue;
        }
        let ends = format!("{} -> {}", m.states[tr.source].path, m.states[tr.target].path);
        let title = if tr.label.contains("->") { ends } else { format!("{} ({ends})", tr.label) };
        let _ = writeln!(out, "/* transition {} */\nstatic void {i}_fire_{k}({st} *st, const {inp} *in, {o} *out)\n{{", comment(&title));
        match tr.kind {
            Kind::Inner => {
                for &child in &m.states[tr.source].children {
                    let _ = writeln!(out, "    if (st->active[{child}]) {{\n        {i}_exit(st, in, out, {child}U);\n    }}");
                }
            }
            _ => {
                let _ = writeln!(out, "    {i}_exit(st, in, out, {}U);", tr.exit_from);
            }
        }
        if let Some(a) = tr.action {
            let id = &m.actions[a].ident;
            let _ = writeln!(out, "    out->{id} = counted(out->{id}); /* {} */", comment(&m.actions[a].text));
            action_code(m, a, "    ", &access, h, out);
        }
        if tr.kind == Kind::SelfLoop {
            let _ = writeln!(out, "    {i}_enter(st, in, out, {}U);", tr.target);
        } else {
            for (step, &s) in tr.entry_path.iter().enumerate() {
                let call = if step + 1 == tr.entry_path.len() { "enter" } else { "enter_one" };
                let _ = writeln!(out, "    {i}_{call}(st, in, out, {s}U);");
            }
        }
        let _ = writeln!(out, "}}\n");
    }
    run_source(plan, m, &access, h, out);
}

fn run_source(plan: &Plan, m: &MachinePlan, access: &Access, h: &mut Helpers, out: &mut String) {
    let t = type_prefix(plan, m);
    let i = &m.ident;
    let n = m.states.len();
    let _ = writeln!(out, "static void {i}_run({t}_state *st, const {t}_inputs *in, {t}_outputs *out)\n{{\n    uint16_t k;\n    (void)in;\n    (void)out;");
    if !m.program().equations.is_empty() {
        let _ = writeln!(out, "    /* equations, in the order written */");
        for e in &m.program().equations {
            let _ = writeln!(out, "    /* {} */", comment(&e.text));
            access.statements(std::slice::from_ref(&e.assign), "    ", h, out);
        }
    }
    for (trigger, order) in &m.dispatch {
        let live: Vec<usize> = order.iter().copied().filter(|&k| m.transitions[k].guard != Guard::Never).collect();
        let (title, condition) = match trigger {
            Trigger::Event(e) => (format!("event \"{}\"", comment(&m.events[*e].text)), format!("in->{}", m.events[*e].ident)),
            Trigger::Timer(tm) => (format!("timed: {}", comment(&m.timers[*tm].label)), String::new()),
            Trigger::Completion => ("completion transitions".to_string(), String::new()),
        };
        let _ = writeln!(out, "    /* {title} */");
        if live.is_empty() {
            let _ = writeln!(out, "    /* (every transition it fires has the guard false) */");
            continue;
        }
        if condition.is_empty() {
            let _ = writeln!(out, "    {{");
        } else {
            let _ = writeln!(out, "    if ({condition}) {{");
        }
        for (slot, &k) in live.iter().enumerate() {
            let tr = &m.transitions[k];
            let mut enabled = format!("st->active[{}]", tr.source);
            if let Trigger::Timer(tm) = tr.trigger {
                let us = m.timers[tm].micros;
                let period = period_macro(plan);
                enabled.push_str(&format!(" && (st->in_state[{}] >= (uint32_t)(({us}UL + {period} - 1UL) / {period}))", tr.source));
            }
            enabled.push_str(&guard_expr(m, &tr.guard, access, h).unwrap_or_default());
            let _ = writeln!(out, "        const bool enabled_{slot} = {enabled};");
        }
        for (slot, &k) in live.iter().enumerate() {
            let tr = &m.transitions[k];
            let _ = writeln!(out, "        if (enabled_{slot} && st->active[{}]) {{\n            {i}_fire_{k}(st, in, out);\n        }}", tr.source);
        }
        let _ = writeln!(out, "    }}");
    }
    let activities: Vec<usize> = (0..n).filter(|&k| !m.states[k].activity.is_empty()).collect();
    if !activities.is_empty() {
        let _ = writeln!(out, "    /* do activities of the active states */");
        for k in activities {
            let _ = writeln!(out, "    if (st->active[{k}]) {{");
            for a in &m.states[k].activity {
                let id = &m.actions[*a].ident;
                let _ = writeln!(out, "        out->{id} = counted(out->{id});");
                action_code(m, *a, "        ", access, h, out);
            }
            let _ = writeln!(out, "    }}");
        }
    }
    let _ = writeln!(
        out,
        "    /* time in state */\n    for (k = 0U; k < {n}U; k++) {{\n        if (st->active[k] && (st->in_state[k] < UINT32_MAX)) {{\n            st->in_state[k]++;\n        }}\n    }}\n}}\n"
    );
}
