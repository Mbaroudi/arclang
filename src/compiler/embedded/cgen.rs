//! Portable C99 from the state machines of a model: `<model>.h` and
//! `<model>.c`, an `init()` / `step()` API over structures the caller owns.
//!
//! The code knows no board: no `malloc`, no OS call, no global variable
//! (the only file-scope objects are `static const` tables), loops bounded by
//! the size of the machine, no recursion. A step reads the inputs, fires
//! what they enable as `execution::Machine` does, counts the actions run
//! and reports the states active; it never touches a register.

use super::plan::{Guard, Kind, MachinePlan, Plan, Trigger};
use std::fmt::Write as _;

/// The generated files: (name, text).
#[derive(Debug, Clone)]
pub struct Generated {
    pub header_name: String,
    pub header: String,
    pub source_name: String,
    pub source: String,
}

/// Text for a C comment: no `*/`, no line break.
pub fn comment(text: &str) -> String {
    text.replace("*/", "* /").replace(['\n', '\r'], " ")
}

pub fn period_macro(plan: &Plan) -> String {
    format!("{}_PERIOD_US", plan.ident.to_uppercase())
}

fn type_prefix(plan: &Plan, machine: &MachinePlan) -> String {
    format!("{}_{}", plan.ident, machine.ident)
}

fn banner(plan: &Plan, what: &str) -> String {
    format!(
        "/*\n * {what}\n * Generated by ArcLang from model \"{}\". Do not edit: regenerate.\n * Portable C99: no dynamic memory, no OS call, no hidden state; the\n * caller owns every structure. See docs/embedded-c.md.\n */\n",
        comment(&plan.model)
    )
}

pub fn generate(plan: &Plan, default_period_us: u64) -> Generated {
    Generated {
        header_name: format!("{}.h", plan.ident),
        header: header(plan, default_period_us),
        source_name: format!("{}.c", plan.ident),
        source: source(plan),
    }
}

fn header(plan: &Plan, default_period_us: u64) -> String {
    let guard = format!("ARCLANG_{}_H", plan.ident.to_uppercase());
    let period = period_macro(plan);
    let mut out = banner(plan, "The behavior of the model: its state machines.");
    let _ = writeln!(out, "#ifndef {guard}\n#define {guard}\n\n#include <stdbool.h>\n#include <stdint.h>\n\n#ifdef __cplusplus\nextern \"C\" {{\n#endif\n");
    let _ = writeln!(out, "/* The step period, in microseconds: timed transitions count steps of it. */\n#ifndef {period}\n#define {period} {default_period_us}UL\n#endif\n#if {period} == 0\n#error \"{period} must be positive\"\n#endif\n");
    for m in &plan.machines {
        let t = type_prefix(plan, m);
        let _ = writeln!(out, "/* state_machine \"{}\" */", comment(&m.name));
        let _ = writeln!(out, "#define {}_STATE_COUNT {}U\n", t.to_uppercase(), m.states.len());
        let _ = writeln!(out, "typedef struct {{");
        for e in &m.events {
            let _ = writeln!(out, "    bool {}; /* event \"{}\": true in the step it occurs */", e.ident, comment(&e.text));
        }
        for c in &m.conditions {
            let _ = writeln!(out, "    bool {}; /* condition \"{}\": whether it holds in the step */", c.ident, comment(&c.text));
        }
        if m.events.is_empty() && m.conditions.is_empty() {
            let _ = writeln!(out, "    uint8_t unused_; /* the machine reads no input */");
        }
        let _ = writeln!(out, "}} {t}_inputs;\n");
        let _ = writeln!(out, "typedef struct {{");
        for s in &m.states {
            let _ = writeln!(out, "    bool {}; /* state {}: active after the step */", s.ident, comment(&s.path));
        }
        for a in &m.actions {
            let _ = writeln!(out, "    uint8_t {}; /* action \"{}\": times run in the step (saturates at 255) */", a.ident, comment(&a.text));
        }
        let _ = writeln!(out, "}} {t}_outputs;\n");
        let _ = writeln!(out, "typedef struct {{\n    bool active[{n}];\n    uint32_t in_state[{n}]; /* steps since the state was entered (saturates) */\n}} {t}_state;\n", n = m.states.len());
    }
    let p = &plan.ident;
    for (kind, name) in [("inputs", "inputs"), ("outputs", "outputs")] {
        let _ = writeln!(out, "typedef struct {{");
        for m in &plan.machines {
            let _ = writeln!(out, "    {}_{kind} {};", type_prefix(plan, m), m.ident);
        }
        let _ = writeln!(out, "}} {p}_{name};\n");
    }
    let _ = writeln!(out, "typedef struct {{\n    bool started;");
    for m in &plan.machines {
        let _ = writeln!(out, "    {}_state {};", type_prefix(plan, m), m.ident);
    }
    let _ = writeln!(out, "}} {p}_state;\n");
    let _ = writeln!(
        out,
        "/* Reset the state: no state is active until the first step, which enters\n   the initial states (their entry actions count in that step). */\nvoid {p}_init({p}_state *state);\n\n/* One step: the initial states on the first one; then, in each machine, the\n   events as declared, the timed transitions, the completion transitions; the\n   do activities of the active states; the outputs. */\nvoid {p}_step({p}_state *state, const {p}_inputs *inputs, {p}_outputs *outputs);\n"
    );
    let _ = writeln!(out, "#ifdef __cplusplus\n}}\n#endif\n\n#endif /* {guard} */");
    out
}

fn guard_expr(m: &MachinePlan, guard: Guard) -> Option<String> {
    match guard {
        Guard::Always => Some(String::new()),
        Guard::Never => None,
        Guard::Condition(i) => Some(format!(" && in->{}", m.conditions[i].ident)),
    }
}

fn source(plan: &Plan) -> String {
    let mut out = banner(plan, "The behavior of the model: its state machines.");
    let _ = writeln!(out, "#include \"{}.h\"\n", plan.ident);
    let _ = writeln!(out, "#define NO_STATE 0xFFFFU\n");
    let any_action = plan.machines.iter().any(|m| !m.actions.is_empty());
    if any_action {
        let _ = writeln!(out, "static uint8_t counted(uint8_t n)\n{{\n    return (n < 255U) ? (uint8_t)(n + 1U) : n;\n}}\n");
    }
    for m in &plan.machines {
        machine_source(plan, m, &mut out);
    }
    let p = &plan.ident;
    let _ = writeln!(out, "void {p}_init({p}_state *state)\n{{\n    uint16_t k;\n    state->started = false;");
    for m in &plan.machines {
        let _ = writeln!(
            out,
            "    for (k = 0U; k < {n}U; k++) {{\n        state->{i}.active[k] = false;\n        state->{i}.in_state[k] = 0U;\n    }}",
            n = m.states.len(),
            i = m.ident
        );
    }
    let _ = writeln!(out, "}}\n");
    let _ = writeln!(out, "void {p}_step({p}_state *state, const {p}_inputs *inputs, {p}_outputs *outputs)\n{{\n    bool starting = !state->started;\n    state->started = true;");
    for m in &plan.machines {
        let i = &m.ident;
        for a in &m.actions {
            let _ = writeln!(out, "    outputs->{i}.{} = 0U;", a.ident);
        }
        let _ = writeln!(out, "    if (starting) {{");
        for &top in &m.machine.tops {
            let _ = writeln!(out, "        {i}_enter(&state->{i}, &outputs->{i}, {top}U); /* {} */", comment(&m.states[top].path));
        }
        let _ = writeln!(out, "    }}\n    {i}_run(&state->{i}, &inputs->{i}, &outputs->{i});");
        for (n, s) in m.states.iter().enumerate() {
            let _ = writeln!(out, "    outputs->{i}.{} = state->{i}.active[{n}];", s.ident);
        }
    }
    let _ = writeln!(out, "}}");
    out
}

fn machine_source(plan: &Plan, m: &MachinePlan, out: &mut String) {
    let t = type_prefix(plan, m);
    let i = &m.ident;
    let n = m.states.len();
    let depth = m.max_depth;
    let st = format!("{t}_state");
    let o = format!("{t}_outputs");
    let _ = writeln!(out, "/* ---- state_machine \"{}\" ---- */\n", comment(&m.name));
    let _ = writeln!(out, "/* States, by index:");
    for (k, s) in m.states.iter().enumerate() {
        let _ = writeln!(out, "     {k}: {}", comment(&s.path));
    }
    let _ = writeln!(out, "*/");
    for note in &m.notes {
        let _ = writeln!(out, "/* note: {} */", comment(note));
    }
    let list = |values: Vec<String>| values.join(", ");
    let index = |v: Option<usize>| v.map(|x| format!("{x}U")).unwrap_or_else(|| "NO_STATE".to_string());
    let has_transitions = !m.transitions.is_empty();
    if has_transitions {
        let _ = writeln!(out, "static const uint16_t {i}_parent[{n}] = {{ {} }};", list(m.states.iter().map(|s| index(s.parent)).collect()));
    }
    let _ = writeln!(out, "static const uint16_t {i}_initial[{n}] = {{ {} }};\n", list(m.states.iter().map(|s| index(s.initial)).collect()));
    let actions_fn = |name: &str, pick: &dyn Fn(&super::plan::StatePlan) -> &Vec<usize>, out: &mut String| {
        let _ = writeln!(out, "static void {i}_{name}(uint16_t s, {o} *out)\n{{");
        let cases: Vec<(usize, &Vec<usize>)> = m.states.iter().enumerate().map(|(k, s)| (k, pick(s))).filter(|(_, a)| !a.is_empty()).collect();
        if cases.is_empty() {
            let _ = writeln!(out, "    (void)s;\n    (void)out;");
        } else {
            let _ = writeln!(out, "    switch (s) {{");
            for (k, acts) in cases {
                let _ = writeln!(out, "    case {k}U: /* {} */", comment(&m.states[k].path));
                for a in acts {
                    let id = &m.actions[*a].ident;
                    let _ = writeln!(out, "        out->{id} = counted(out->{id});");
                }
                let _ = writeln!(out, "        break;");
            }
            let _ = writeln!(out, "    default:\n        break;\n    }}");
        }
        let _ = writeln!(out, "}}\n");
    };
    actions_fn("entry_actions", &|s| &s.entry, out);
    let _ = writeln!(
        out,
        "static void {i}_enter_one({st} *st, {o} *out, uint16_t s)\n{{\n    st->active[s] = true;\n    st->in_state[s] = 0U;\n    {i}_entry_actions(s, out);\n}}\n"
    );
    let _ = writeln!(
        out,
        "/* Enter s and the initial states under it, down to a leaf. */\nstatic void {i}_enter({st} *st, {o} *out, uint16_t s)\n{{\n    uint16_t current = s;\n    uint16_t level;\n    for (level = 0U; level < {depth}U; level++) {{\n        {i}_enter_one(st, out, current);\n        if ({i}_initial[current] == NO_STATE) {{\n            break;\n        }}\n        current = {i}_initial[current];\n    }}\n}}\n"
    );
    if has_transitions {
        actions_fn("exit_actions", &|s| &s.exit, out);
        let _ = writeln!(
            out,
            "/* Exit s and the active states under it, deepest first. */\nstatic void {i}_exit({st} *st, {o} *out, uint16_t s)\n{{\n    uint16_t leaf = s;\n    uint16_t level;\n    uint16_t k;\n    bool deeper;\n    for (level = 0U; level < {depth}U; level++) {{\n        deeper = false;\n        for (k = 0U; k < {n}U; k++) {{\n            if (({i}_parent[k] == leaf) && st->active[k]) {{\n                leaf = k;\n                deeper = true;\n                break;\n            }}\n        }}\n        if (!deeper) {{\n            break;\n        }}\n    }}\n    for (level = 0U; level < {depth}U; level++) {{\n        if (st->active[leaf]) {{\n            st->active[leaf] = false;\n            {i}_exit_actions(leaf, out);\n        }}\n        if ((leaf == s) || ({i}_parent[leaf] == NO_STATE)) {{\n            break;\n        }}\n        leaf = {i}_parent[leaf];\n    }}\n}}\n"
        );
    }
    for (k, tr) in m.transitions.iter().enumerate() {
        if tr.guard == Guard::Never {
            continue;
        }
        let ends = format!("{} -> {}", m.states[tr.source].path, m.states[tr.target].path);
        let title = if tr.label.contains("->") { ends } else { format!("{} ({ends})", tr.label) };
        let _ = writeln!(out, "/* transition {} */\nstatic void {i}_fire_{k}({st} *st, {o} *out)\n{{", comment(&title));
        match tr.kind {
            Kind::Inner => {
                for &child in &m.states[tr.source].children {
                    let _ = writeln!(out, "    if (st->active[{child}]) {{\n        {i}_exit(st, out, {child}U);\n    }}");
                }
            }
            _ => {
                let _ = writeln!(out, "    {i}_exit(st, out, {}U);", tr.exit_from);
            }
        }
        if let Some(a) = tr.action {
            let id = &m.actions[a].ident;
            let _ = writeln!(out, "    out->{id} = counted(out->{id}); /* {} */", comment(&m.actions[a].text));
        }
        if tr.kind == Kind::SelfLoop {
            let _ = writeln!(out, "    {i}_enter(st, out, {}U);", tr.target);
        } else {
            for (step, &s) in tr.entry_path.iter().enumerate() {
                let call = if step + 1 == tr.entry_path.len() { "enter" } else { "enter_one" };
                let _ = writeln!(out, "    {i}_{call}(st, out, {s}U);");
            }
        }
        let _ = writeln!(out, "}}\n");
    }
    run_source(plan, m, out);
}

fn run_source(plan: &Plan, m: &MachinePlan, out: &mut String) {
    let t = type_prefix(plan, m);
    let i = &m.ident;
    let n = m.states.len();
    let _ = writeln!(out, "static void {i}_run({t}_state *st, const {t}_inputs *in, {t}_outputs *out)\n{{\n    uint16_t k;\n    (void)in;\n    (void)out;");
    for (trigger, order) in &m.dispatch {
        let live: Vec<usize> = order.iter().copied().filter(|&k| m.transitions[k].guard != Guard::Never).collect();
        let (title, condition) = match trigger {
            Trigger::Event(e) => (format!("event \"{}\"", comment(&m.events[*e].text)), format!("in->{}", m.events[*e].ident)),
            Trigger::Timer(tm) => (format!("timed: {}", comment(&m.timers[*tm].label)), String::new()),
            Trigger::Completion => ("completion transitions".to_string(), String::new()),
        };
        let _ = writeln!(out, "    /* {title} */");
        if live.is_empty() {
            let _ = writeln!(out, "    /* (every transition it fires has the guard false) */");
            continue;
        }
        if condition.is_empty() {
            let _ = writeln!(out, "    {{");
        } else {
            let _ = writeln!(out, "    if ({condition}) {{");
        }
        for (slot, &k) in live.iter().enumerate() {
            let tr = &m.transitions[k];
            let mut enabled = format!("st->active[{}]", tr.source);
            if let Trigger::Timer(tm) = tr.trigger {
                let us = m.timers[tm].micros;
                let period = period_macro(plan);
                enabled.push_str(&format!(" && (st->in_state[{}] >= (uint32_t)(({us}UL + {period} - 1UL) / {period}))", tr.source));
            }
            enabled.push_str(&guard_expr(m, tr.guard).unwrap_or_default());
            let _ = writeln!(out, "        const bool enabled_{slot} = {enabled};");
        }
        for (slot, &k) in live.iter().enumerate() {
            let tr = &m.transitions[k];
            let _ = writeln!(out, "        if (enabled_{slot} && st->active[{}]) {{\n            {i}_fire_{k}(st, out);\n        }}", tr.source);
        }
        let _ = writeln!(out, "    }}");
    }
    let activities: Vec<usize> = (0..n).filter(|&k| !m.states[k].activity.is_empty()).collect();
    if !activities.is_empty() {
        let _ = writeln!(out, "    /* do activities of the active states */");
        for k in activities {
            let _ = writeln!(out, "    if (st->active[{k}]) {{");
            for a in &m.states[k].activity {
                let id = &m.actions[*a].ident;
                let _ = writeln!(out, "        out->{id} = counted(out->{id});");
            }
            let _ = writeln!(out, "    }}");
        }
    }
    let _ = writeln!(
        out,
        "    /* time in state */\n    for (k = 0U; k < {n}U; k++) {{\n        if (st->active[k] && (st->in_state[k] < UINT32_MAX)) {{\n            st->in_state[k]++;\n        }}\n    }}\n}}\n"
    );
}
