//! Portable C99 from the state machines of a model: `<model>.h` and
//! `<model>.c`, an `init()` / `step()` API over structures the caller owns.
//!
//! The code knows no board: no `malloc`, no OS call, no global variable
//! (the only file-scope objects are `static const` tables), loops bounded by
//! the size of the machine, no recursion. A step reads the inputs, fires
//! what they enable as `execution::Machine` does, counts the actions run
//! and reports the states active; it never touches a register.

use super::cexpr::{self, Access, Helpers};
use super::plan::{Guard, MachinePlan, Plan, Trigger};
use crate::compiler::execution::machine::{Alternative, EntryOp, Next, Segment};
use crate::compiler::execution::expr::{BlockKind, Direction};
use std::fmt::Write as _;

/// The generated files: (name, text).
#[derive(Debug, Clone)]
pub struct Generated {
    pub header_name: String,
    pub header: String,
    pub source_name: String,
    pub source: String,
}

/// Text for a C comment: no `*/`, no line break.
pub fn comment(text: &str) -> String {
    text.replace("*/", "* /").replace(['\n', '\r'], " ")
}

pub fn period_macro(plan: &Plan) -> String {
    format!("{}_PERIOD_US", plan.ident.to_uppercase())
}

/// The macro of an event's code: `<MODEL>_<MACHINE>_EV_<EVENT>`.
pub fn event_macro(prefix: &str, event_ident: &str) -> String {
    super::plan::bounded(&format!("{}_{}", prefix.to_uppercase(), event_ident.to_uppercase()), 63)
}

fn type_prefix(plan: &Plan, machine: &MachinePlan) -> String {
    format!("{}_{}", plan.ident, machine.ident)
}

fn pid_type(plan: &Plan) -> String {
    format!("{}_pid_state", plan.ident)
}

fn banner(plan: &Plan, what: &str) -> String {
    format!(
        "/*\n * {what}\n * Generated by ArcLang from model \"{}\". Do not edit: regenerate.\n * Portable C99: no dynamic memory, no OS call, no hidden state; the\n * caller owns every structure. See docs/embedded-c.md.\n */\n",
        comment(&plan.model)
    )
}

pub fn generate(plan: &Plan, default_period_us: u64) -> Generated {
    Generated {
        header_name: format!("{}.h", plan.ident),
        header: header(plan, default_period_us),
        source_name: format!("{}.c", plan.ident),
        source: source(plan),
    }
}

fn header(plan: &Plan, default_period_us: u64) -> String {
    let guard = format!("ARCLANG_{}_H", plan.ident.to_uppercase());
    let period = period_macro(plan);
    let mut out = banner(plan, "The behavior of the model: its state machines.");
    let _ = writeln!(out, "#ifndef {guard}\n#define {guard}\n\n#include <stdbool.h>\n#include <stdint.h>\n\n#ifdef __cplusplus\nextern \"C\" {{\n#endif\n");
    if plan.machines.iter().any(|m| super::cexpr::uses_pid(m.program())) {
        let _ = writeln!(out, "/* The state of a PID block. */\ntypedef struct {{\n    double integral;\n    double previous;\n    bool primed;\n}} {};\n", pid_type(plan));
    }
    let _ = writeln!(out, "/* The step period, in microseconds: timed transitions count steps of it. */\n#ifndef {period}\n#define {period} {default_period_us}UL\n#endif\n#if {period} == 0\n#error \"{period} must be positive\"\n#endif\n");
    for m in &plan.machines {
        let t = type_prefix(plan, m);
        let _ = writeln!(out, "/* state_machine \"{}\" */", comment(&m.name));
        let _ = writeln!(out, "#define {}_STATE_COUNT {}U\n", t.to_uppercase(), m.states.len());
        let upper = t.to_uppercase();
        if !m.events.is_empty() {
            let _ = writeln!(out, "/* The events of the machine, as posted to its queue. */");
            for (n, e) in m.events.iter().enumerate() {
                let _ = writeln!(out, "#define {} {n}U /* event \"{}\" */", event_macro(&t, &e.ident), comment(&e.text));
            }
            let _ = writeln!(out, "/* How many events one step takes, at most. */\n#ifndef {upper}_QUEUE_SIZE\n#define {upper}_QUEUE_SIZE 16U\n#endif\n");
        }
        let _ = writeln!(out, "typedef struct {{");
        if !m.events.is_empty() {
            let _ = writeln!(out, "    uint16_t queue[{upper}_QUEUE_SIZE]; /* the events of the step, in the order they arrived */\n    uint8_t queued; /* how many: the caller empties it (0) before posting the next step's */");
        }
        for c in &m.conditions {
            let _ = writeln!(out, "    bool {}; /* condition \"{}\": whether it holds in the step */", c.ident, comment(&c.text));
        }
        let program = m.program();
        let unit = |v: &crate::compiler::execution::expr::Variable| v.unit.as_ref().map(|u| format!(" [{u}]")).unwrap_or_default();
        for (i, v) in program.inputs() {
            let _ = writeln!(out, "    {} {}; /* in variable \"{}\"{}: its value in the step */", v.ty.c(), m.variables[i].ident, comment(&v.name), comment(&unit(v)));
        }
        if m.events.is_empty() && m.conditions.is_empty() && program.inputs().next().is_none() {
            let _ = writeln!(out, "    uint8_t unused_; /* the machine reads no input */");
        }
        let _ = writeln!(out, "}} {t}_inputs;\n");
        let _ = writeln!(out, "typedef struct {{");
        for s in &m.states {
            let _ = writeln!(out, "    bool {}; /* state {}: active after the step */", s.ident, comment(&s.path));
        }
        for a in &m.actions {
            let _ = writeln!(out, "    uint8_t {}; /* action \"{}\": times run in the step (saturates at 255) */", a.ident, comment(&a.text));
        }
        for (i, v) in program.variables.iter().enumerate() {
            let _ = writeln!(out, "    {} {}; /* variable \"{}\"{}: its value after the step */", v.ty.c(), m.variables[i].ident, comment(&v.name), comment(&unit(v)));
        }
        for b in &m.budgets {
            let _ = writeln!(out, "    bool {}; /* budget {} of transition {}: its source active longer than it */", b.ident, comment(&b.written), comment(&b.label));
        }
        let _ = writeln!(out, "}} {t}_outputs;\n");
        let _ = writeln!(out, "typedef struct {{\n    bool active[{n}];\n    uint32_t in_state[{n}]; /* steps since the state was entered (saturates) */", n = m.states.len());
        for (i, v) in program.variables.iter().enumerate().filter(|(_, v)| v.direction != crate::compiler::execution::expr::Direction::In) {
            let _ = writeln!(out, "    {} {}; /* variable \"{}\"{} */", v.ty.c(), m.variables[i].ident, comment(&v.name), comment(&unit(v)));
        }
        for b in 0..program.blocks.len() {
            let _ = writeln!(out, "    {} blk_{b}; /* the state of a block of the equations */", super::cexpr::block_field(program, b, &pid_type(plan)));
        }
        for (h, deep, owner, (lo, hi)) in m.histories() {
            let what = format!("{} of {}", m.states[h].path, m.states[owner].path);
            if deep {
                let _ = writeln!(out, "    bool has_{h}; /* deep history {}: remembered */
    bool deep_{h}[{}]; /* its region's active states when last exited */", comment(&what), hi - lo + 1);
            } else {
                let _ = writeln!(out, "    uint16_t hist_{h}; /* shallow history {}: the state last active in its region */", comment(&what));
            }
        }
        if m.terminates() {
            let _ = writeln!(out, "    bool terminated; /* a terminate pseudo-state was reached */");
        }
        let _ = writeln!(out, "}} {t}_state;\n");
    }
    let p = &plan.ident;
    for (kind, name) in [("inputs", "inputs"), ("outputs", "outputs")] {
        let _ = writeln!(out, "typedef struct {{");
        for m in &plan.machines {
            let _ = writeln!(out, "    {}_{kind} {};", type_prefix(plan, m), m.ident);
        }
        let _ = writeln!(out, "}} {p}_{name};\n");
    }
    let _ = writeln!(out, "typedef struct {{\n    bool started;");
    for m in &plan.machines {
        let _ = writeln!(out, "    {}_state {};", type_prefix(plan, m), m.ident);
    }
    let _ = writeln!(out, "}} {p}_state;\n");
    let _ = writeln!(
        out,
        "/* Reset the state: no state is active until the first step, which enters\n   the initial states (their entry actions count in that step). */\nvoid {p}_init({p}_state *state);\n\n/* One step: the initial states on the first one; then, in each machine, the\n   equations, the events of its queue in the order they arrived, the timed\n   transitions, the completion transitions; the do activities of the active\n   states; the outputs. */\nvoid {p}_step({p}_state *state, const {p}_inputs *inputs, {p}_outputs *outputs);\n"
    );
    for m in plan.machines.iter().filter(|m| !m.events.is_empty()) {
        let t = type_prefix(plan, m);
        let _ = writeln!(out, "/* Post an event of state_machine \"{}\" for the next step, after those posted\n   before it; false (and dropped) when the queue is full. */\nbool {t}_post({t}_inputs *inputs, uint16_t event);\n", comment(&m.name));
    }
    let _ = writeln!(out, "#ifdef __cplusplus\n}}\n#endif\n\n#endif /* {guard} */");
    out
}

/// The code of an action, when it is code, as lines at `indent`.
fn action_code(m: &MachinePlan, action: usize, indent: &str, access: &Access, h: &mut Helpers, out: &mut String) {
    if let Some(code) = m.program().actions.get(m.actions[action].text.trim()) {
        access.statements(code, indent, h, out);
    }
}

fn source(plan: &Plan) -> String {
    let mut h = Helpers::default();
    let mut body = String::new();
    for m in &plan.machines {
        machine_source(plan, m, &mut h, &mut body);
    }
    let p = &plan.ident;
    let _ = writeln!(body, "void {p}_init({p}_state *state)\n{{\n    uint16_t k;\n    state->started = false;");
    for m in &plan.machines {
        let i = &m.ident;
        let _ = writeln!(body, "    for (k = 0U; k < {n}U; k++) {{\n        state->{i}.active[k] = false;\n        state->{i}.in_state[k] = 0U;\n    }}", n = m.states.len());
        let program = m.program();
        for (n, v) in program.variables.iter().enumerate().filter(|(_, v)| v.direction != Direction::In) {
            let _ = writeln!(body, "    state->{i}.{} = {};", m.variables[n].ident, cexpr::constant(v.initial));
        }
        for (h, deep, _, (lo, hi)) in m.histories() {
            if deep {
                let _ = writeln!(body, "    state->{i}.has_{h} = false;\n    for (k = 0U; k < {}U; k++) {{\n        state->{i}.deep_{h}[k] = false;\n    }}", hi - lo + 1);
            } else {
                let _ = writeln!(body, "    state->{i}.hist_{h} = NO_STATE;");
            }
        }
        if m.terminates() {
            let _ = writeln!(body, "    state->{i}.terminated = false;");
        }
        for (b, block) in program.blocks.iter().enumerate() {
            match block.kind {
                BlockKind::Delay => {
                    let _ = writeln!(body, "    state->{i}.blk_{b} = {};", cexpr::constant(block.initial));
                }
                BlockKind::Integrator { .. } => {
                    let _ = writeln!(body, "    state->{i}.blk_{b} = 0.0;");
                }
                BlockKind::Pid { .. } => {
                    let _ = writeln!(body, "    state->{i}.blk_{b}.integral = 0.0;\n    state->{i}.blk_{b}.previous = 0.0;\n    state->{i}.blk_{b}.primed = false;");
                }
            }
        }
    }
    let _ = writeln!(body, "}}\n");
    let _ = writeln!(body, "void {p}_step({p}_state *state, const {p}_inputs *inputs, {p}_outputs *outputs)\n{{\n    bool starting = !state->started;\n    state->started = true;");
    for m in &plan.machines {
        let i = &m.ident;
        for a in &m.actions {
            let _ = writeln!(body, "    outputs->{i}.{} = 0U;", a.ident);
        }
        let _ = writeln!(body, "    if (starting) {{\n        {i}_start(&state->{i}, &inputs->{i}, &outputs->{i});\n    }}\n    {i}_run(&state->{i}, &inputs->{i}, &outputs->{i});");
        for (n, s) in m.states.iter().enumerate() {
            let _ = writeln!(body, "    outputs->{i}.{} = state->{i}.active[{n}];", s.ident);
        }
        for (n, v) in m.program().variables.iter().enumerate() {
            let from = if v.direction == Direction::In { "inputs" } else { "state" };
            let _ = writeln!(body, "    outputs->{i}.{f} = {from}->{i}.{f};", f = m.variables[n].ident);
        }
        let period = period_macro(plan);
        for b in &m.budgets {
            let _ = writeln!(body, "    outputs->{i}.{} = state->{i}.active[{s}] && (state->{i}.in_state[{s}] > (({us}UL + {period} - 1UL) / {period})); /* budget {} */", b.ident, comment(&b.written), s = b.source, us = b.micros);
        }
    }
    let _ = writeln!(body, "}}");
    for m in plan.machines.iter().filter(|m| !m.events.is_empty()) {
        let t = type_prefix(plan, m);
        let _ = writeln!(body, "\nbool {t}_post({t}_inputs *inputs, uint16_t event)\n{{\n    bool posted = false;\n    if ((inputs->queued < {u}_QUEUE_SIZE) && (event < {n}U)) {{\n        inputs->queue[inputs->queued] = event;\n        inputs->queued++;\n        posted = true;\n    }}\n    return posted;\n}}", u = t.to_uppercase(), n = m.events.len());
    }

    let mut out = banner(plan, "The behavior of the model: its state machines.");
    let _ = writeln!(out, "#include \"{}.h\"\n", plan.ident);
    if plan.machines.iter().any(|m| !m.program().is_empty()) {
        let _ = writeln!(out, "/* The arithmetic is the model's: no contraction of a * b + c into one rounding. */\n#if defined(__clang__)\n#pragma STDC FP_CONTRACT OFF\n#endif\n");
    }
    if plan.machines.iter().any(|m| !m.histories().is_empty()) {
        let _ = writeln!(out, "#define NO_STATE 0xFFFFU\n");
    }
    let any_action = plan.machines.iter().any(|m| !m.actions.is_empty());
    if any_action {
        let _ = writeln!(out, "static uint8_t counted(uint8_t n)\n{{\n    return (n < 255U) ? (uint8_t)(n + 1U) : n;\n}}\n");
    }
    out.push_str(&cexpr::definitions(&h, &pid_type(plan)));
    out.push_str(&body);
    out
}

fn guard_c(m: &MachinePlan, text: &str, access: &Access, h: &mut Helpers) -> String {
    match m.guard(text) {
        Guard::Always => "true".to_string(),
        Guard::Never => "false".to_string(),
        Guard::Condition(c) => format!("in->{}", m.conditions[c].ident),
        Guard::Code(code) => access.expr(&m.program().guards[&code], h),
    }
}

/// The guards of a branch and of the choices after it, as one C condition.
fn holds_c(m: &MachinePlan, guards: &[String], segment: &Segment, access: &Access, h: &mut Helpers) -> String {
    let mut parts: Vec<String> = guards.iter().filter(|g| m.guard(g) != Guard::Always).map(|g| guard_c(m, g, access, h)).collect();
    if let Next::Choice { branches, .. } = &segment.next {
        let any: Vec<String> = branches.iter().map(|b| holds_c(m, &b.guards, &b.segment, access, h)).collect();
        if !any.iter().any(|a| a == "true") {
            parts.push(format!("({})", any.join(" || ")));
        }
    }
    match parts.len() {
        0 => "true".to_string(),
        1 => parts.remove(0),
        _ => parts.iter().map(|p| if p.starts_with('(') { p.clone() } else { format!("({p})") }).collect::<Vec<_>>().join(" && "),
    }
}

fn never(m: &MachinePlan, guards: &[String]) -> bool {
    guards.iter().any(|g| m.guard(g) == Guard::Never)
}

fn transition_actions(m: &MachinePlan, transitions: &[usize], indent: &str, access: &Access, h: &mut Helpers, out: &mut String) {
    for &t in transitions {
        if let Some(a) = m.transitions[t].action {
            let id = &m.actions[a].ident;
            let _ = writeln!(out, "{indent}out->{id} = counted(out->{id}); /* {}: {} */", comment(&m.transitions[t].label), comment(&m.actions[a].text));
            action_code(m, a, indent, access, h, out);
        }
    }
}

fn entry_c(m: &MachinePlan, ops: &[EntryOp], indent: &str, access: &Access, h: &mut Helpers, out: &mut String) {
    let i = &m.ident;
    for op in ops {
        match op {
            EntryOp::Enter(s) => {
                let _ = writeln!(out, "{indent}{i}_enter_one(st, in, out, {s}U); /* {} */", comment(&m.states[*s].path));
            }
            EntryOp::Action(t) => transition_actions(m, &[*t], indent, access, h, out),
            EntryOp::History { pseudo, default } => {
                let deep = m.histories().into_iter().find(|x| x.0 == *pseudo);
                match deep {
                    Some((p, true, _, (lo, hi))) => {
                        let _ = writeln!(out, "{indent}if (st->has_{p}) {{ /* deep history {} */\n{indent}    uint16_t k;\n{indent}    for (k = {lo}U; k <= {hi}U; k++) {{\n{indent}        if (st->deep_{p}[k - {lo}U]) {{\n{indent}            {i}_enter_one(st, in, out, k);\n{indent}        }}\n{indent}    }}\n{indent}}} else {{", comment(&m.states[p].path));
                    }
                    Some((p, false, _, _)) => {
                        let _ = writeln!(out, "{indent}if (st->hist_{p} != NO_STATE) {{ /* shallow history {} */\n{indent}    {i}_enter_default(st, in, out, st->hist_{p});\n{indent}}} else {{", comment(&m.states[p].path));
                    }
                    None => {
                        let _ = writeln!(out, "{indent}{{");
                    }
                }
                entry_c(m, default, &format!("{indent}    "), access, h, out);
                let _ = writeln!(out, "{indent}}}");
            }
        }
    }
}

fn segment_c(m: &MachinePlan, segment: &Segment, indent: &str, access: &Access, h: &mut Helpers, out: &mut String) {
    let i = &m.ident;
    for &(lo, hi) in &segment.exit {
        let _ = writeln!(out, "{indent}{i}_exit_range(st, in, out, {lo}U, {hi}U);");
    }
    transition_actions(m, &segment.transitions, indent, access, h, out);
    match &segment.next {
        Next::Enter(ops) => entry_c(m, ops, indent, access, h, out),
        Next::Terminate => {
            let _ = writeln!(out, "{indent}{{ /* terminate: no exit action, nothing active any more */\n{indent}    uint16_t k;\n{indent}    for (k = 0U; k < {}U; k++) {{\n{indent}        st->active[k] = false;\n{indent}    }}\n{indent}    st->terminated = true;\n{indent}}}", m.states.len());
        }
        Next::Choice { pseudo, branches } => {
            let _ = writeln!(out, "{indent}/* choice {}: the first branch that holds now, else the first */", comment(&m.states[*pseudo].path));
            if branches.len() == 1 {
                segment_c(m, &branches[0].segment, indent, access, h, out);
                return;
            }
            for (n, b) in branches.iter().enumerate() {
                let cond = holds_c(m, &b.guards, &b.segment, access, h);
                let _ = writeln!(out, "{indent}{}if ({cond}) {{", if n == 0 { "" } else { "} else " });
                segment_c(m, &b.segment, &format!("{indent}    "), access, h, out);
            }
            let _ = writeln!(out, "{indent}}} else {{");
            segment_c(m, &branches[0].segment, &format!("{indent}    "), access, h, out);
            let _ = writeln!(out, "{indent}}}");
        }
    }
}

fn machine_source(plan: &Plan, m: &MachinePlan, h: &mut Helpers, out: &mut String) {
    let t = type_prefix(plan, m);
    let i = &m.ident;
    let n = m.states.len();
    let st = format!("{t}_state");
    let inp = format!("{t}_inputs");
    let o = format!("{t}_outputs");
    let period = period_macro(plan);
    let access = Access { machine: m, state: "st", inputs: "in", period: &period };
    let histories = m.histories();
    let shallow = histories.iter().any(|x| !x.1);
    let _ = writeln!(out, "/* ---- state_machine \"{}\" ---- */\n", comment(&m.name));
    let _ = writeln!(out, "/* States, by index (a state, then the states of its regions):");
    for (k, s) in m.states.iter().enumerate() {
        let pseudo = m.machine.states[k].pseudo.map(|p| format!(" (pseudo-state: {p:?}, never active)")).unwrap_or_default();
        let _ = writeln!(out, "     {k}: {}{}", comment(&s.path), comment(&pseudo));
    }
    let _ = writeln!(out, "*/");
    for note in &m.notes {
        let _ = writeln!(out, "/* note: {} */", comment(note));
    }
    let list = |values: Vec<String>| values.join(", ");
    let index = |v: Option<usize>| v.map(|x| format!("{x}U")).unwrap_or_else(|| "NO_STATE".to_string());
    if !histories.is_empty() {
        let _ = writeln!(out, "static const uint16_t {i}_parent[{n}] = {{ {} }};", list(m.states.iter().map(|s| index(s.parent)).collect()));
    }
    let _ = writeln!(out);
    let actions_fn = |name: &str, pick: &dyn Fn(&super::plan::StatePlan) -> &Vec<usize>, out: &mut String, h: &mut Helpers| {
        let _ = writeln!(out, "static void {i}_{name}({st} *st, const {inp} *in, {o} *out, uint16_t s)\n{{");
        let cases: Vec<(usize, &Vec<usize>)> = m.states.iter().enumerate().map(|(k, s)| (k, pick(s))).filter(|(_, a)| !a.is_empty()).collect();
        let _ = writeln!(out, "    (void)st;\n    (void)in;");
        if cases.is_empty() {
            let _ = writeln!(out, "    (void)s;\n    (void)out;");
        } else {
            let _ = writeln!(out, "    switch (s) {{");
            for (k, acts) in cases {
                let _ = writeln!(out, "    case {k}U: /* {} */", comment(&m.states[k].path));
                for a in acts {
                    let id = &m.actions[*a].ident;
                    let _ = writeln!(out, "        out->{id} = counted(out->{id});");
                    action_code(m, *a, "        ", &access, h, out);
                }
                let _ = writeln!(out, "        break;");
            }
            let _ = writeln!(out, "    default:\n        break;\n    }}");
        }
        let _ = writeln!(out, "}}\n");
    };
    actions_fn("entry_actions", &|s| &s.entry, out, h);
    let _ = writeln!(out, "static void {i}_enter_one({st} *st, const {inp} *in, {o} *out, uint16_t s)\n{{\n    st->active[s] = true;\n    st->in_state[s] = 0U;\n    {i}_entry_actions(st, in, out, s);\n}}\n");
    if shallow {
        let last = list(m.machine.states.iter().map(|s| format!("{}U", s.last)).collect());
        // Whether a state is the initial state of its region.
        let starts = list(
            (0..n)
                .map(|k| {
                    let node = &m.machine.states[k];
                    let first = match node.parent {
                        Some(p) => m.machine.states[p].regions[node.region].initial,
                        None => m.machine.top_regions[node.region].initial,
                    };
                    (if first == Some(k) { "true" } else { "false" }).to_string()
                })
                .collect(),
        );
        let _ = writeln!(
            out,
            "/* Enter s and the initial states of the regions under it, in the order of the states. */\nstatic void {i}_enter_default({st} *st, const {inp} *in, {o} *out, uint16_t s)\n{{\n    static const uint16_t {i}_last[{n}] = {{ {last} }};\n    static const bool {i}_starts[{n}] = {{ {starts} }};\n    uint16_t k;\n    {i}_enter_one(st, in, out, s);\n    for (k = (uint16_t)(s + 1U); k <= {i}_last[s]; k++) {{\n        if ({i}_starts[k] && st->active[{i}_parent[k]]) {{\n            {i}_enter_one(st, in, out, k);\n        }}\n    }}\n}}\n"
        );
    }
    if !m.compounds.is_empty() {
        actions_fn("exit_actions", &|s| &s.exit, out, h);
        let _ = writeln!(out, "/* Exit the active states of lo..hi, the last first; the history of a state exited is kept first. */\nstatic void {i}_exit_range({st} *st, const {inp} *in, {o} *out, uint16_t lo, uint16_t hi)\n{{\n    uint16_t n;\n    uint16_t k;");
        for &(p, deep, owner, (lo, hi)) in &histories {
            let low = if owner == 0 { String::new() } else { format!("(lo <= {owner}U) && ") };
            let _ = writeln!(out, "    if ({low}({owner}U <= hi) && st->active[{owner}]) {{");
            if deep {
                let _ = writeln!(out, "        bool any = false;\n        for (k = {lo}U; k <= {hi}U; k++) {{\n            if (st->active[k]) {{\n                any = true;\n            }}\n        }}\n        if (any) {{\n            for (k = {lo}U; k <= {hi}U; k++) {{\n                st->deep_{p}[k - {lo}U] = st->active[k];\n            }}\n            st->has_{p} = true;\n        }}");
            } else {
                let _ = writeln!(out, "        for (k = {lo}U; k <= {hi}U; k++) {{\n            if (st->active[k] && ({i}_parent[k] == {owner}U)) {{\n                st->hist_{p} = k;\n                break;\n            }}\n        }}");
            }
            let _ = writeln!(out, "    }}");
        }
        let _ = writeln!(out, "    for (n = 0U; n <= (uint16_t)(hi - lo); n++) {{\n        k = (uint16_t)(hi - n);\n        if (st->active[k]) {{\n            st->active[k] = false;\n            {i}_exit_actions(st, in, out, k);\n        }}\n    }}\n}}\n");
    }
    // The start: the initial state of every top-level region, down to the leaves.
    let _ = writeln!(out, "static void {i}_start({st} *st, const {inp} *in, {o} *out)\n{{");
    for &top in &m.machine.tops {
        entry_c(m, &m.machine.default_entry(top), "    ", &access, h, out);
    }
    let _ = writeln!(out, "}}\n");
    for (c, cp) in m.compounds.iter().enumerate() {
        let compound = &cp.compound;
        let head = &m.transitions[compound.head];
        let ends = format!("{} -> {}", m.states[head.source].path, m.states[head.target].path);
        let title = if head.label.contains("->") { ends } else { format!("{} ({ends})", head.label) };
        let _ = writeln!(out, "/* transition {} */\nstatic void {i}_fire_{c}({st} *st, const {inp} *in, {o} *out, uint8_t alternative)\n{{\n    (void)in;\n    (void)out;", comment(&title));
        let live: Vec<(usize, &Alternative)> = compound.alternatives.iter().enumerate().filter(|(_, a)| !never(m, &a.guards)).collect();
        if live.len() == 1 {
            let _ = writeln!(out, "    (void)alternative;");
            segment_c(m, &live[0].1.segment, "    ", &access, h, out);
        } else {
            let _ = writeln!(out, "    switch (alternative) {{");
            for (a, alt) in &live {
                let _ = writeln!(out, "    case {}U:", a + 1);
                segment_c(m, &alt.segment, "        ", &access, h, out);
                let _ = writeln!(out, "        break;");
            }
            let _ = writeln!(out, "    default:\n        break;\n    }}");
        }
        let _ = writeln!(out, "}}\n");
    }
    run_source(plan, m, &access, h, out);
}

fn run_source(plan: &Plan, m: &MachinePlan, access: &Access, h: &mut Helpers, out: &mut String) {
    let t = type_prefix(plan, m);
    let i = &m.ident;
    let n = m.states.len();
    let mut handlers = String::new();
    let mut run = String::new();
    let out_final = out;
    let out = &mut run;
    let _ = writeln!(out, "static void {i}_run({t}_state *st, const {t}_inputs *in, {t}_outputs *out)\n{{\n    uint16_t k;\n    (void)in;\n    (void)out;");
    if m.terminates() {
        // One exit (MISRA C 2012 rule 15.5): a terminated machine does nothing.
        let _ = writeln!(out, "    if (!st->terminated) {{");
    }
    if !m.program().equations.is_empty() {
        let _ = writeln!(out, "    /* equations, in the order written */");
        for e in &m.program().equations {
            let _ = writeln!(out, "    /* {} */", comment(&e.text));
            access.statements(std::slice::from_ref(&e.assign), "    ", h, out);
        }
    }
    // The events: in the order of the queue, each by its handler.
    let handled: Vec<usize> = m.dispatch.iter().filter_map(|(trigger, _)| if let Trigger::Event(e) = trigger { Some(*e) } else { None }).collect();
    if !m.events.is_empty() {
        let upper = t.to_uppercase();
        let _ = writeln!(out, "    /* the events, in the order they arrived */\n    for (k = 0U; (k < (uint16_t)in->queued) && (k < {upper}_QUEUE_SIZE); k++) {{\n        switch (in->queue[k]) {{");
        for &e in &handled {
            let _ = writeln!(out, "        case {}:\n            {i}_on_{e}(st, in, out);\n            break;", event_macro(&t, &m.events[e].ident));
        }
        let _ = writeln!(out, "        default:\n            break;\n        }}\n    }}");
    }
    for (trigger, order) in &m.dispatch {
        let live: Vec<usize> = order.iter().copied().filter(|&c| m.compounds[c].compound.alternatives.iter().any(|a| !never(m, &a.guards))).collect();
        let (title, condition) = match trigger {
            Trigger::Event(e) => (format!("event \"{}\"", comment(&m.events[*e].text)), String::new()),
            Trigger::Timer(tm) => (format!("timed: {}", comment(&m.timers[*tm].label)), String::new()),
            Trigger::Completion => ("completion transitions".to_string(), String::new()),
        };
        // An event's transitions go in its handler, called from the queue.
        let mut group = String::new();
        let out: &mut String = if let Trigger::Event(e) = trigger {
            let _ = writeln!(handlers, "/* event \"{}\": its transitions */\nstatic void {i}_on_{e}({t}_state *st, const {t}_inputs *in, {t}_outputs *out)\n{{\n    (void)in;\n    (void)out;", comment(&m.events[*e].text));
            &mut group
        } else {
            &mut *out
        };
        let _ = writeln!(out, "    /* {title} */");
        if live.is_empty() {
            let _ = writeln!(out, "    /* (every transition it fires has the guard false) */");
            if matches!(trigger, Trigger::Event(_)) {
                handlers.push_str(&group);
                let _ = writeln!(handlers, "}}\n");
            }
            continue;
        }
        if condition.is_empty() {
            let _ = writeln!(out, "    {{");
        } else {
            let _ = writeln!(out, "    if ({condition}) {{");
        }
        for slot in 0..live.len() {
            let _ = writeln!(out, "        uint8_t alt_{slot} = 0U;");
        }
        let sources_active = |c: usize| m.compounds[c].compound.sources.iter().map(|s| format!("st->active[{s}]")).collect::<Vec<_>>().join(" && ");
        for (slot, &c) in live.iter().enumerate() {
            let compound = &m.compounds[c].compound;
            let mut enabled = sources_active(c);
            if let Trigger::Timer(tm) = m.compounds[c].trigger {
                let us = m.timers[tm].micros;
                let period = period_macro(plan);
                enabled.push_str(&format!(" && (st->in_state[{}] >= (({us}UL + {period} - 1UL) / {period}))", m.transitions[compound.head].source));
            }
            let _ = writeln!(out, "        if ({enabled}) {{");
            let alternatives: Vec<(usize, &Alternative)> = compound.alternatives.iter().enumerate().filter(|(_, a)| !never(m, &a.guards)).collect();
            for (n, (a, alt)) in alternatives.iter().enumerate() {
                let cond = holds_c(m, &alt.guards, &alt.segment, access, h);
                if cond == "true" {
                    // An unguarded alternative ends the list.
                    if n == 0 {
                        let _ = writeln!(out, "            alt_{slot} = {}U;", a + 1);
                    } else {
                        let _ = writeln!(out, "            else {{\n                alt_{slot} = {}U;\n            }}", a + 1);
                    }
                    break;
                }
                let _ = writeln!(out, "            {}if ({cond}) {{\n                alt_{slot} = {}U;\n            }}", if n == 0 { "" } else { "else " }, a + 1);
            }
            let _ = writeln!(out, "        }}");
        }
        for (slot, &c) in live.iter().enumerate() {
            let _ = writeln!(out, "        if ((alt_{slot} != 0U) && {}) {{\n            {i}_fire_{c}(st, in, out, alt_{slot});\n        }}", sources_active(c));
        }
        let _ = writeln!(out, "    }}");
        if matches!(trigger, Trigger::Event(_)) {
            handlers.push_str(&group);
            let _ = writeln!(handlers, "}}\n");
        }
    }
    let activities: Vec<usize> = (0..n).filter(|&k| !m.states[k].activity.is_empty()).collect();
    if !activities.is_empty() {
        let _ = writeln!(out, "    /* do activities of the active states */");
        for k in activities {
            let _ = writeln!(out, "    if (st->active[{k}]) {{");
            for a in &m.states[k].activity {
                let id = &m.actions[*a].ident;
                let _ = writeln!(out, "        out->{id} = counted(out->{id});");
                action_code(m, *a, "        ", access, h, out);
            }
            let _ = writeln!(out, "    }}");
        }
    }
    let _ = writeln!(
        out,
        "    /* time in state */\n    for (k = 0U; k < {n}U; k++) {{\n        if (st->active[k] && (st->in_state[k] < UINT32_MAX)) {{\n            st->in_state[k]++;\n        }}\n    }}\n}}\n"
    );
    if m.terminates() {
        // Close the `if (!st->terminated)` around the body.
        let end = run.rfind("}\n").expect("the end of run");
        run.insert_str(end, "    }\n");
    }
    out_final.push_str(&handlers);
    out_final.push_str(&run);
}
