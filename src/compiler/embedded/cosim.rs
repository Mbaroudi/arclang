//! Co-simulation in OMSimulator (`arclang cosim`): a case that `execute:`s,
//! run as a standard co-simulation instead of ArcLang's own loop. The
//! behavior is exported as an FMI 2.0 co-simulation FMU (`export -f fmu`,
//! compiled here), the plant of the case as another (a Modelica plant built
//! by OpenModelica behind a wrapper that makes its variables FMU outputs, or
//! the FMU the case gives), the case's input vectors as a table; the three
//! are connected in an SSP (System Structure and Parameterization 1.0)
//! package and OMSimulator, OpenModelica's FMI master, runs it at the
//! machine's period. The run is then judged as `arclang sil` judges the C:
//! the case's expectations on it, and step by step against the model's own
//! loop, the reference.
//!
//! The SSP is kept (`--keep`): it opens in any SSP tool, the FMUs inside.
//! OMSimulator does not apply an SSP connection's linear transformation, so
//! values cross the connections in the machine's units: the Modelica
//! wrapper converts to and from SI itself, and a given FMU must use the
//! units of the machine variables it is wired to.

