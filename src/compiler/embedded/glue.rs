//! The glue of a binding: `<model>_<binding>_io.h/.c`, the only generated
//! code that calls `arclang_io.h`. It reads the bound channels into the
//! inputs of the machine, writes its outputs to the bound channels, and
//! runs one cycle: read, step, write, kick the watchdog.

use super::binding::{Binding, Edge, Origin, Sink, Source, Target};
use super::cgen::{comment, period_macro};
use super::plan::Plan;
use std::collections::BTreeMap;
use std::fmt::Write as _;

#[derive(Debug, Clone)]
pub struct Glue {
    pub header_name: String,
    pub header: String,
    pub source_name: String,
    pub source: String,
}

/// Bytes read from a UART in one period, at most.
pub const UART_BURST: u32 = 16;

pub fn generate(plan: &Plan, binding: &Binding) -> Glue {
    let b = &binding.ident;
    let p = &plan.ident;
    let guard = format!("ARCLANG_{}_IO_H", b.to_uppercase());
    let banner = format!(
        "/*\n * I/O glue of io_binding \"{}\" (state_machine \"{}\"), every {} us.\n * Generated by ArcLang from model \"{}\". Do not edit: regenerate.\n * The only generated code that calls arclang_io.h.\n */\n",
        comment(&binding.name),
        comment(&plan.machines[binding.machine].name),
        binding.period_us,
        comment(&plan.model)
    );
    let edges: Vec<u16> = dedup(binding.inputs.iter().filter_map(|i| match i.source {
        Source::GpioEdge(pin, _) => Some(pin),
        _ => None,
    }));
    let latches: Vec<u32> = dedup(binding.inputs.iter().filter_map(|i| match (i.target, i.source) {
        (Target::Condition(_), Source::Can(id)) => Some(id),
        _ => None,
    }));
    let mut header = banner.clone();
    let _ = writeln!(header, "#ifndef {guard}\n#define {guard}\n\n#include \"arclang_io.h\"\n#include \"{p}.h\"\n\n#ifdef __cplusplus\nextern \"C\" {{\n#endif\n");
    let _ = writeln!(header, "#define {}_PERIOD_US {}UL\n", b.to_uppercase(), binding.period_us);
    let _ = writeln!(header, "/* What the glue keeps between cycles (the caller owns it). */\ntypedef struct {{");
    for pin in &edges {
        let _ = writeln!(header, "    bool gpio_{pin}; /* level of gpio {pin} at the last cycle, for its edges */");
    }
    for id in &latches {
        let _ = writeln!(header, "    bool can_{id:x}; /* first byte of the last frame 0x{id:X} not zero */");
    }
    if edges.is_empty() && latches.is_empty() {
        let _ = writeln!(header, "    uint8_t unused_;");
    }
    let _ = writeln!(header, "}} {b}_glue;\n");
    let _ = writeln!(
        header,
        "/* Edges count from a low level, latches from false. */\nvoid {b}_glue_init({b}_glue *glue);\n\n/* Read the bound channels into the inputs of the machine; the other\n   inputs are left as they are. A channel in error leaves its events false\n   and its conditions false; the first error is returned. */\narclang_io_status {b}_read({b}_glue *glue, {p}_inputs *inputs);\n\n/* Write the outputs to the bound channels; the first error is returned. */\narclang_io_status {b}_write(const {p}_outputs *outputs);\n\n/* One cycle: read; if that failed, return its error without stepping;\n   step; write;{} The caller waits the period\n   (arclang_io_clock_wait_period) between cycles. */\narclang_io_status {b}_cycle({b}_glue *glue, {p}_state *state, {p}_inputs *inputs, {p}_outputs *outputs);\n",
        if binding.watchdog { " kick the watchdog when everything succeeded." } else { "" }
    );
    let _ = writeln!(header, "#ifdef __cplusplus\n}}\n#endif\n\n#endif /* {guard} */");

    let mut source = banner;
    let _ = writeln!(source, "#include \"{b}_io.h\"\n");
    let period = period_macro(plan);
    let _ = writeln!(source, "#if {period} != {}UL\n#error \"{p}.c is compiled for another period than io_binding {} ({} us): define {period}={}\"\n#endif\n", binding.period_us, comment(&binding.name), binding.period_us, binding.period_us);
    let _ = writeln!(source, "#ifndef ARCLANG_IO_UART_BURST\n#define ARCLANG_IO_UART_BURST {UART_BURST}U\n#endif\n");
    let _ = writeln!(source, "static void first_error(arclang_io_status *status, arclang_io_status result)\n{{\n    if ((*status == ARCLANG_IO_OK) && (result != ARCLANG_IO_OK)) {{\n        *status = result;\n    }}\n}}\n");
    if binding.inputs.iter().any(|i| matches!(i.target, Target::Event(_))) {
        let _ = writeln!(source, "/* An event the queue had no room for is an error of the read. */\nstatic void posted(arclang_io_status *status, bool ok)\n{{\n    if (!ok) {{\n        first_error(status, ARCLANG_IO_ERR_FULL);\n    }}\n}}\n");
    }
    let _ = writeln!(source, "void {b}_glue_init({b}_glue *glue)\n{{");
    for pin in &edges {
        let _ = writeln!(source, "    glue->gpio_{pin} = false;");
    }
    for id in &latches {
        let _ = writeln!(source, "    glue->can_{id:x} = false;");
    }
    if edges.is_empty() && latches.is_empty() {
        let _ = writeln!(source, "    glue->unused_ = 0U;");
    }
    let _ = writeln!(source, "}}\n");
    read_source(plan, binding, &mut source);
    write_source(plan, binding, &mut source);
    let _ = writeln!(source, "arclang_io_status {b}_cycle({b}_glue *glue, {p}_state *state, {p}_inputs *inputs, {p}_outputs *outputs)\n{{\n    arclang_io_status status = {b}_read(glue, inputs);\n    if (status != ARCLANG_IO_OK) {{\n        return status;\n    }}\n    {p}_step(state, inputs, outputs);\n    status = {b}_write(outputs);");
    if binding.watchdog {
        let _ = writeln!(source, "    if (status != ARCLANG_IO_OK) {{\n        return status;\n    }}\n    return arclang_io_watchdog_kick();\n}}");
    } else {
        let _ = writeln!(source, "    return status;\n}}");
    }
    Glue { header_name: format!("{b}_io.h"), header, source_name: format!("{b}_io.c"), source }
}

fn dedup<T: Ord + Copy>(items: impl Iterator<Item = T>) -> Vec<T> {
    let mut out: Vec<T> = items.collect();
    out.sort();
    out.dedup();
    out
}

fn read_source(plan: &Plan, binding: &Binding, out: &mut String) {
    let b = &binding.ident;
    let p = &plan.ident;
    let m = &plan.machines[binding.machine];
    let field = |target: Target| match target {
        Target::Event(e) => format!("in->{}", m.events[e].ident),
        Target::Condition(c) => format!("in->{}", m.conditions[c].ident),
    };
    let _ = writeln!(out, "arclang_io_status {b}_read({b}_glue *glue, {p}_inputs *inputs)\n{{\n    arclang_io_status status = ARCLANG_IO_OK;");
    if binding.inputs.is_empty() {
        let _ = writeln!(out, "    (void)glue;\n    (void)inputs;\n    return status;\n}}\n");
        return;
    }
    let _ = writeln!(out, "    arclang_io_status result;\n    {p}_{}_inputs *in = &inputs->{};\n    (void)glue;", m.ident, m.ident);
    let t = format!("{p}_{}", m.ident);
    let post = |target: Target| match target {
        Target::Event(e) => format!("posted(&status, {t}_post(in, {}_{}))", t.to_uppercase(), m.events[e].ident.to_uppercase()),
        Target::Condition(_) => unreachable!("an event"),
    };
    if binding.inputs.iter().any(|i| matches!(i.target, Target::Event(_))) {
        let _ = writeln!(out, "    /* events: posted in the order the glue reads them (gpio edges by pin, CAN\n       frames by identifier, UART bytes as they arrived), the queue emptied first */\n    in->queued = 0U;");
    }
    // gpio: one read per pin.
    let mut pins: BTreeMap<u16, Vec<&super::binding::Input>> = BTreeMap::new();
    let mut analog: BTreeMap<u16, Vec<&super::binding::Input>> = BTreeMap::new();
    let mut frames: BTreeMap<u32, Vec<&super::binding::Input>> = BTreeMap::new();
    let mut ports: BTreeMap<u16, Vec<&super::binding::Input>> = BTreeMap::new();
    for input in &binding.inputs {
        match input.source {
            Source::GpioLevel(pin) | Source::GpioEdge(pin, _) => pins.entry(pin).or_default().push(input),
            Source::Adc { channel, .. } => analog.entry(channel).or_default().push(input),
            Source::Can(id) => frames.entry(id).or_default().push(input),
            Source::Uart { port, .. } => ports.entry(port).or_default().push(input),
        }
    }
    for (pin, inputs) in &pins {
        let _ = writeln!(out, "    {{ /* gpio {pin} */\n        bool level = false;\n        result = arclang_io_gpio_read({pin}U, &level);\n        first_error(&status, result);\n        if (result == ARCLANG_IO_OK) {{");
        let mut edge = false;
        for input in inputs {
            match input.source {
                Source::GpioLevel(_) => {
                    let _ = writeln!(out, "            {} = level; /* {} */", field(input.target), comment(&input.written));
                }
                Source::GpioEdge(_, Edge::Rising) => {
                    edge = true;
                    let _ = writeln!(out, "            if (level && !glue->gpio_{pin}) {{ /* {} */\n                {};\n            }}", comment(&input.written), post(input.target));
                }
                Source::GpioEdge(_, Edge::Falling) => {
                    edge = true;
                    let _ = writeln!(out, "            if (!level && glue->gpio_{pin}) {{ /* {} */\n                {};\n            }}", comment(&input.written), post(input.target));
                }
                _ => {}
            }
        }
        if edge {
            let _ = writeln!(out, "            glue->gpio_{pin} = level;");
        }
        let _ = writeln!(out, "        }}");
        let levels: Vec<_> = inputs.iter().filter(|i| matches!(i.source, Source::GpioLevel(_))).collect();
        if !levels.is_empty() {
            let _ = writeln!(out, "        else {{");
            for input in levels {
                let _ = writeln!(out, "            {} = false;", field(input.target));
            }
            let _ = writeln!(out, "        }}");
        }
        let _ = writeln!(out, "    }}");
    }
    for (channel, inputs) in &analog {
        let _ = writeln!(out, "    {{ /* adc {channel} */\n        uint16_t raw = 0U;\n        result = arclang_io_adc_read({channel}U, &raw);\n        first_error(&status, result);");
        for input in inputs {
            if let Source::Adc { above, threshold, .. } = input.source {
                let op = if above { ">" } else { "<" };
                let _ = writeln!(out, "        {} = (result == ARCLANG_IO_OK) && (raw {op} {threshold}U); /* {} */", field(input.target), comment(&input.written));
            }
        }
        let _ = writeln!(out, "    }}");
    }
    for (id, inputs) in &frames {
        let _ = writeln!(out, "    {{ /* can 0x{id:X} */\n        uint8_t data[8] = {{0U}};\n        uint8_t length = 0U;\n        bool received = false;\n        result = arclang_io_can_receive(0x{id:X}UL, data, &length, &received);\n        first_error(&status, result);");
        let latched = inputs.iter().any(|i| matches!(i.target, Target::Condition(_)));
        if latched {
            let _ = writeln!(out, "        if ((result == ARCLANG_IO_OK) && received) {{\n            glue->can_{id:x} = (length > 0U) && (data[0] != 0U);\n        }}");
        }
        for input in inputs {
            match input.target {
                Target::Event(_) => {
                    let _ = writeln!(out, "        if ((result == ARCLANG_IO_OK) && received) {{ /* {} */\n            {};\n        }}", comment(&input.written), post(input.target));
                }
                Target::Condition(_) => {
                    let _ = writeln!(out, "        {} = (result == ARCLANG_IO_OK) && glue->can_{id:x}; /* {} */", field(input.target), comment(&input.written));
                }
            }
        }
        let _ = writeln!(out, "    }}");
    }
    for (port, inputs) in &ports {
        let _ = writeln!(out, "    {{ /* uart {port} */\n        uint16_t n;\n        for (n = 0U; n < ARCLANG_IO_UART_BURST; n++) {{\n            uint8_t byte = 0U;\n            bool received = false;\n            result = arclang_io_uart_read({port}U, &byte, &received);\n            first_error(&status, result);\n            if ((result != ARCLANG_IO_OK) || !received) {{\n                break;\n            }}");
        for input in inputs {
            if let Source::Uart { byte, .. } = input.source {
                let _ = writeln!(out, "            if (byte == 0x{byte:02X}U) {{ /* {} */\n                {};\n            }}", comment(&input.written), post(input.target));
            }
        }
        let _ = writeln!(out, "        }}\n    }}");
    }
    let _ = writeln!(out, "    return status;\n}}\n");
}

fn write_source(plan: &Plan, binding: &Binding, out: &mut String) {
    let b = &binding.ident;
    let p = &plan.ident;
    let m = &plan.machines[binding.machine];
    let _ = writeln!(out, "arclang_io_status {b}_write(const {p}_outputs *outputs)\n{{\n    arclang_io_status status = ARCLANG_IO_OK;");
    if binding.outputs.is_empty() {
        let _ = writeln!(out, "    (void)outputs;\n    return status;\n}}\n");
        return;
    }
    let _ = writeln!(out, "    const {p}_{}_outputs *out = &outputs->{};", m.ident, m.ident);
    for output in &binding.outputs {
        let value = match output.origin {
            Origin::State(s) => format!("(uint8_t)(out->{} ? 1U : 0U)", m.states[s].ident),
            Origin::Action(a) => format!("out->{}", m.actions[a].ident),
        };
        let _ = writeln!(out, "    {{ /* {} */\n        const uint8_t value = {value};", comment(&output.written));
        match output.sink {
            Sink::Gpio(pin) => {
                let _ = writeln!(out, "        first_error(&status, arclang_io_gpio_write({pin}U, value != 0U));");
            }
            Sink::Pwm(ch, duty) => {
                let _ = writeln!(out, "        first_error(&status, arclang_io_pwm_write({ch}U, (value != 0U) ? {duty}U : 0U));");
            }
            Sink::Dac(ch, raw) => {
                let _ = writeln!(out, "        first_error(&status, arclang_io_dac_write({ch}U, (value != 0U) ? {raw}U : 0U));");
            }
            Sink::Can(id) => {
                let _ = writeln!(out, "        uint8_t data[8] = {{0U}};\n        data[0] = value;\n        first_error(&status, arclang_io_can_send(0x{id:X}UL, data, 1U));");
            }
            Sink::Uart(port, byte) => {
                let _ = writeln!(out, "        if (value != 0U) {{\n            first_error(&status, arclang_io_uart_write({port}U, 0x{byte:02X}U));\n        }}");
            }
        }
        let _ = writeln!(out, "    }}");
    }
    let _ = writeln!(out, "    return status;\n}}\n");
}
