//! The reader of the C the compiler generates (`embedded/cgen.rs`): a header
//! with one group of declarations per machine, a source with one group of
//! functions per machine. The generator writes one statement per line, which
//! is what this reader relies on; a file it does not recognise is refused,
//! and a construct it does not read is a note, never a guess.

use super::{Generated, Machine, Recovered, State, Transition, Variable};
use regex::Regex;
use std::collections::BTreeMap;

fn re(pattern: &str) -> Regex {
    Regex::new(pattern).expect("a pattern of the reader")
}

fn first(text: &str, pattern: &str) -> Option<String> {
    re(pattern).captures(text).map(|c| c[1].to_string())
}

/// What the header says of a machine beyond its variables and states.
#[derive(Default)]
struct Names {
    /// `cond_<ident>` → the condition as the model writes it.
    conditions: BTreeMap<String, String>,
    /// `act_<ident>` → the action as the model writes it.
    actions: BTreeMap<String, String>,
    /// `v_<ident>` → the index of the variable.
    variables: BTreeMap<String, usize>,
    /// `bud_<ident>` → the ends of the transition it is the budget of, as the model names them, and its time as written.
    budgets: BTreeMap<String, (String, String, String)>,
}

pub(super) fn read(generated: &Generated) -> Result<Recovered, String> {
    let model = first(generated.header, r#"Generated by ArcLang from model "(.+)"\."#)
        .ok_or_else(|| format!("{} is not a header the compiler generated: it does not say `Generated by ArcLang from model`", generated.header_name))?;
    let prefix = first(generated.header, r"#ifndef ARCLANG_(\w+)_H").ok_or_else(|| format!("{}: no include guard `ARCLANG_<MODEL>_H`", generated.header_name))?.to_lowercase();
    let mut recovered = Recovered { model, ..Recovered::default() };
    let mut names: Vec<Names> = Vec::new();
    header(generated, &prefix, &mut recovered, &mut names)?;
    if recovered.machines.is_empty() {
        return Err(format!("{} declares no state machine", generated.header_name));
    }
    for (machine, names) in recovered.machines.iter_mut().zip(&names) {
        code(generated, &prefix, machine, names, &mut recovered.notes);
    }
    recovered.notes.push("not in the code: the regions of a machine (its states are recovered, not their grouping), whether a variable is `out` or `const`, the range of a variable".to_string());
    Ok(recovered)
}

fn c_type(ty: &str) -> Option<&'static str> {
    Some(match ty {
        "double" => "Real",
        "int32_t" => "Integer",
        "bool" => "Boolean",
        _ => return None,
    })
}

fn header(generated: &Generated, prefix: &str, recovered: &mut Recovered, names: &mut Vec<Names>) -> Result<(), String> {
    let machine_line = re(r#"^/\* state_machine "(.+)" \*/$"#);
    let closing = re(&format!(r"^\}} {prefix}_(\w+)_(inputs|outputs|state);$"));
    let condition = re(r#"^\s*bool cond_(\w+); /\* condition "(.+)": whether"#);
    let action = re(r#"^\s*uint8_t act_(\w+); /\* action "(.+)": times run"#);
    let state = re(r"^\s*bool st_\w+; /\* state (.+): active after the step \*/");
    let budget = re(r"^\s*bool bud_(\w+); /\* budget (.+) of transition (.+) -> (.+): its source active longer than it \*/");
    let input = re(r#"^\s*(\w+) v_(\w+); /\* in variable "(.+?)"(?: \[(.+?)\])?: its value in the step \*/"#);
    let kept = re(r#"^\s*(\w+) v_(\w+); /\* variable "(.+?)"(?: \[(.+?)\])? \*/"#);
    let mut body: Vec<(usize, &str)> = Vec::new();
    let mut open = false;
    for (at, line) in generated.header.lines().enumerate() {
        if let Some(found) = machine_line.captures(line) {
            recovered.machines.push(Machine { name: found[1].to_string(), line: at + 1, ..Machine::default() });
            names.push(Names::default());
            continue;
        }
        if line == "typedef struct {" {
            open = true;
            body.clear();
            continue;
        }
        if !open {
            continue;
        }
        let Some(end) = closing.captures(line) else {
            if line.starts_with('}') {
                open = false;
            } else {
                body.push((at + 1, line));
            }
            continue;
        };
        open = false;
        // The structures of a machine follow its `state_machine` comment; those of the model follow them all.
        let (Some(machine), Some(names)) = (recovered.machines.last_mut(), names.last_mut()) else { continue };
        if machine.ident.is_empty() {
            machine.ident = end[1].to_string();
        } else if machine.ident != end[1] {
            continue;
        }
        for &(number, field) in &body {
            if let Some(found) = condition.captures(field) {
                names.conditions.insert(found[1].to_string(), found[2].to_string());
            } else if let Some(found) = action.captures(field) {
                names.actions.insert(found[1].to_string(), found[2].to_string());
            } else if let Some(found) = budget.captures(field) {
                names.budgets.insert(found[1].to_string(), (found[3].to_string(), found[4].to_string(), found[2].to_string()));
            } else if let Some(found) = state.captures(field) {
                machine.states.push(State { path: found[1].to_string(), ..State::default() });
            } else if let Some(found) = input.captures(field).filter(|_| &end[2] == "inputs").or_else(|| kept.captures(field).filter(|_| &end[2] == "state")) {
                let ty = c_type(&found[1]).ok_or_else(|| format!("{}:{number}: a variable of type `{}`, which the generator does not write", generated.header_name, &found[1]))?;
                names.variables.insert(found[2].to_string(), machine.variables.len());
                machine.variables.push(Variable { name: found[3].to_string(), ty, unit: found.get(4).map(|u| u.as_str().to_string()), input: &end[2] == "inputs", initial: None, from: None, line: number });
            }
        }
    }
    Ok(())
}

/// What a block of alternatives says of the transition it fires.
#[derive(Default, Clone)]
struct Alternative {
    from: usize,
    guard: Option<String>,
    after_us: Option<u64>,
    /// The time as the comment above the block spells it.
    written: Option<String>,
}

/// Whether a time written in a comment (`10 min`) is the time the code counts.
fn same_time(written: &str, microseconds: u64) -> bool {
    crate::compiler::quantity::Quantity::parse(written).is_ok_and(|q| (q.canonical() * 1e6 - microseconds as f64).abs() < 0.5)
}

fn code(generated: &Generated, prefix: &str, machine: &mut Machine, names: &Names, notes: &mut Vec<String>) {
    let id = machine.ident.clone();
    let function = re(r"^static void (\w+)\(");
    let step = format!("void {prefix}_{id}_step(");
    let enter = re(&format!(r"^\s*{id}_enter_one\(st, in, out, (\d+)U\);"));
    let case = re(r"^\s*case (\d+)U:");
    let act = re(r"^\s*out->act_(\w+) = counted\(");
    let event = re(r#"^/\* event "(.+)": its transitions \*/$"#);
    let active = re(r"^\s*if \(st->active\[(\d+)\]\) \{$");
    let timed = re(r"^\s*if \(st->active\[(\d+)\] && \(st->in_state\[\d+\] >= \(\((\d+)UL \+ ");
    let condition = re(r"^\s*if \((.+)\) \{$");
    let chosen = re(r"^\s*alt_(\d+) = (\d+)U;$");
    let fired = re(&format!(r"^\s*{id}_fire_(\d+)\(st, in, out, alt_(\d+)\);$"));
    let comment = re(r"^\s*/\* (.+) \*/$");
    let initial = re(&format!(r"^\s*state->{id}\.v_(\w+) = (.+);$"));
    let wired = re(r#"^\s*wired\.v_(\w+) = .+; /\* from state_machine "(.+)", (\w+) \*/$"#);
    let over_budget = re(&format!(r"^\s*outputs->{id}\.bud_(\w+) = state->{id}\.active\[(\d+)\] && \(state->{id}\.in_state\[\d+\] > \(\((\d+)UL \+ "));
    // (the source state, microseconds, the ends as the model names them)
    let mut budgets: Vec<(usize, u64, (String, String, String))> = Vec::new();

    let mut current = String::new();
    let mut in_step = false;
    let mut state_of_case: Option<usize> = None;
    let mut start: Vec<usize> = Vec::new();
    // fire index → (line, actions, the states it enters)
    let mut fires: BTreeMap<usize, (usize, Vec<String>, Vec<usize>)> = BTreeMap::new();
    let mut fire: Option<usize> = None;
    let mut trigger: Option<String> = None;
    let mut pending_event: Option<String> = None;
    let mut alternatives: BTreeMap<usize, Alternative> = BTreeMap::new();
    let mut open = Alternative::default();
    let mut section = "";
    let mut timed_text: Option<String> = None;
    let mut held_comment: Option<String> = None;
    let mut activity_of: Option<usize> = None;
    let mut found: Vec<(usize, Option<String>, Alternative)> = Vec::new();

    for (at, line) in generated.code.lines().enumerate() {
        if let Some(name) = event.captures(line) {
            pending_event = Some(name[1].to_string());
            continue;
        }
        if let Some(name) = function.captures(line) {
            current = name[1].to_string();
            in_step = false;
            state_of_case = None;
            fire = current.strip_prefix(&format!("{id}_fire_")).and_then(|n| n.parse().ok());
            if let Some(n) = fire {
                fires.insert(n, (at + 1, Vec::new(), Vec::new()));
            }
            trigger = if current.starts_with(&format!("{id}_on_")) { pending_event.take() } else { None };
            section = "";
            continue;
        }
        if line.starts_with("void ") {
            current.clear();
            in_step = line.starts_with(&step);
            continue;
        }
        if in_step {
            if let Some(wire) = wired.captures(line) {
                if let Some(&index) = names.variables.get(&wire[1]) {
                    machine.variables[index].from = Some((wire[2].to_string(), wire[3].to_string()));
                }
            }
            if let Some(over) = over_budget.captures(line) {
                if let (Some(ends), Ok(from), Ok(time)) = (names.budgets.get(&over[1]), over[2].parse(), over[3].parse()) {
                    budgets.push((from, time, ends.clone()));
                }
            }
            continue;
        }
        if current.is_empty() {
            // The initial values are set in the model's `init`, after every machine.
            if let Some(value) = initial.captures(line) {
                if let Some(&index) = names.variables.get(&value[1]) {
                    machine.variables[index].initial = Some(value[2].to_string());
                }
            }
            continue;
        }
        let Some(part) = current.strip_prefix(&format!("{id}_")) else { continue };
        let action_of = |line: &str| act.captures(line).map(|found| names.actions.get(&found[1]).cloned().unwrap_or_else(|| found[1].replace('_', " ")));
        match part {
            "entry_actions" | "exit_actions" => {
                if let Some(index) = case.captures(line) {
                    state_of_case = index[1].parse().ok();
                } else if let (Some(text), Some(state)) = (action_of(line), state_of_case.and_then(|s| machine.states.get_mut(s))) {
                    if part == "entry_actions" { state.entry.push(text) } else { state.exit.push(text) }
                }
            }
            "start" => start.extend(enter.captures(line).and_then(|e| e[1].parse::<usize>().ok())),
            _ if fire.is_some() => {
                let entry = fires.get_mut(&fire.unwrap_or_default()).expect("the fire function being read");
                if let Some(text) = action_of(line) {
                    entry.1.push(text);
                } else if let Some(state) = enter.captures(line).and_then(|e| e[1].parse::<usize>().ok()) {
                    entry.2.push(state);
                }
            }
            _ => {
                // `run`, and the function of each event: equations, then blocks of alternatives.
                if part == "run" {
                    if let Some(text) = comment.captures(line) {
                        let text = text[1].to_string();
                        section = match text.as_str() {
                            "equations, in the order written" => "equations",
                            "the events, in the order they arrived" => "events",
                            "completion transitions" => "completion",
                            "do activities of the active states" => "activities",
                            "time in state" => "time",
                            other if other.starts_with("timed: ") => {
                                timed_text = other.strip_prefix("timed: after ").map(str::to_string);
                                "timed"
                            }
                            _ => {
                                if section == "equations" {
                                    held_comment = Some(text);
                                }
                                section
                            }
                        };
                        continue;
                    }
                    if section == "equations" {
                        // The statement under the comment is what computes it.
                        machine.equations.extend(held_comment.take());
                        continue;
                    }
                    if section == "activities" {
                        if let Some(state) = active.captures(line) {
                            activity_of = state[1].parse().ok();
                        } else if let (Some(text), Some(state)) = (action_of(line), activity_of.and_then(|s| machine.states.get_mut(s))) {
                            state.activity.push(text);
                        }
                        continue;
                    }
                    if section == "events" || section == "time" {
                        continue;
                    }
                }
                if line.contains("uint8_t alt_") {
                    continue;
                }
                if let Some(state) = timed.captures(line) {
                    open = Alternative { from: state[1].parse().unwrap_or_default(), guard: None, after_us: state[2].parse().ok(), written: timed_text.clone() };
                } else if let Some(state) = active.captures(line) {
                    open = Alternative { from: state[1].parse().unwrap_or_default(), guard: None, after_us: None, written: None };
                } else if let Some(choice) = chosen.captures(line) {
                    if &choice[2] != "1" {
                        notes.push(format!("{}:{}: state_machine \"{}\": a transition with several branches (a junction or a choice), which this reader does not recover", generated.code_name, at + 1, machine.name));
                    }
                    alternatives.insert(choice[1].parse().unwrap_or_default(), open.clone());
                } else if let Some(transition) = fired.captures(line) {
                    if let Some(alternative) = alternatives.get(&transition[2].parse().unwrap_or_default()) {
                        found.push((transition[1].parse().unwrap_or_default(), trigger.clone(), alternative.clone()));
                    }
                } else if let Some(guard) = condition.captures(line).filter(|g| !g[1].starts_with("(alt_")) {
                    open.guard = Some(guard[1].to_string());
                }
            }
        }
    }

    // Where the machine starts, and where each composite state does: a state
    // entered right after the one that holds it.
    machine.initial = start.first().copied();
    let together = start.iter().filter(|&&s| machine.states.get(s).is_some_and(|state| !state.path.contains('.'))).count();
    if together > 1 {
        notes.push(format!("state_machine \"{}\" starts in {together} states at once: it has regions, which this reader does not recover yet; its recovery will not be proven", machine.name));
    }
    let mut sequences: Vec<&Vec<usize>> = vec![&start];
    sequences.extend(fires.values().map(|(_, _, entered)| entered));
    let mut starts: Vec<(usize, String)> = Vec::new();
    for entered in sequences {
        for pair in entered.windows(2) {
            let (Some(outer), Some(inner)) = (machine.states.get(pair[0]), machine.states.get(pair[1])) else { continue };
            if let Some(leaf) = inner.path.strip_prefix(&format!("{}.", outer.path)).filter(|leaf| !leaf.contains('.')) {
                starts.push((pair[0], leaf.to_string()));
            }
        }
    }
    for (state, leaf) in starts {
        machine.states[state].initial.get_or_insert(leaf);
    }

    found.sort_by_key(|(index, _, _)| *index);
    for (index, trigger, alternative) in found {
        let Some((line, actions, entered)) = fires.get(&index) else { continue };
        let Some(&to) = entered.first() else {
            notes.push(format!("{}:{line}: state_machine \"{}\": a transition that enters no state (an internal transition), not recovered", generated.code_name, machine.name));
            continue;
        };
        machine.transitions.push(Transition {
            from: alternative.from,
            to,
            trigger,
            guard: alternative.guard.as_deref().map(|guard| expression(guard, machine, names)),
            after_us: alternative.after_us,
            budget_us: None,
            time_text: alternative.after_us.zip(alternative.written.clone()).filter(|(time, written)| same_time(written, *time)).map(|(_, written)| written),
            actions: actions.clone(),
            line: *line,
        });
    }
    // A budget is the time a transition has to leave its source: it is the
    // budget of the transition from that state to the state its name says.
    for (from, time, (_, to, written)) in budgets {
        let target = |t: &Transition| machine.states.get(t.to).is_some_and(|s| s.path == to || leaf(&s.path) == to);
        match machine.transitions.iter().position(|t| t.from == from && t.budget_us.is_none() && target(t)) {
            Some(index) => {
                machine.transitions[index].budget_us = Some(time);
                machine.transitions[index].time_text = same_time(&written, time).then_some(written);
            }
            None => notes.push(format!("state_machine \"{}\": a budget of {time} us on a transition to '{to}' that was not recovered", machine.name)),
        }
    }
}

/// The last name of a state's path.
fn leaf(path: &str) -> &str {
    path.rsplit('.').next().unwrap_or(path)
}

/// A condition of the C as the model writes it: the variables by their names,
/// a prose condition by its text, `and`, `or` and `not` for the C operators.
fn expression(guard: &str, machine: &Machine, names: &Names) -> String {
    let mut text = guard.trim().to_string();
    while wrapped(&text) {
        text = text[1..text.len() - 1].trim().to_string();
    }
    if let Some(prose) = re(r"^in->cond_(\w+)$").captures(&text).and_then(|c| names.conditions.get(&c[1])) {
        return prose.clone();
    }
    let unit_of = |name: &str| machine.variables.iter().find(|v| v.name == name).and_then(|v| v.unit.clone());
    let text = re(r"(?:in|st|out)->v_(\w+)").replace_all(&text, |found: &regex::Captures| names.variables.get(&found[1]).map(|&i| machine.variables[i].name.clone()).unwrap_or_else(|| found[1].to_string()));
    let text = text.replace("&&", "and").replace("||", "or");
    let text = re(r"!([^=])").replace_all(&text, "not $1");
    let text = re(r"\b(\d+)\.0\b").replace_all(&text, "$1");
    // A number compared with a variable is in the unit of that variable.
    let text = re(r"\b([A-Za-z_]\w*) (>=|<=|==|!=|>|<) (-?\d+(?:\.\d+)?)\b").replace_all(&text, |found: &regex::Captures| match unit_of(&found[1]) {
        Some(unit) => format!("{} {} {} {unit}", &found[1], &found[2], &found[3]),
        None => found[0].to_string(),
    });
    text.into_owned()
}

/// Whether the text is one parenthesis around everything.
fn wrapped(text: &str) -> bool {
    if !(text.starts_with('(') && text.ends_with(')')) {
        return false;
    }
    let mut depth = 0usize;
    for (at, c) in text.char_indices() {
        match c {
            '(' => depth += 1,
            ')' => {
                depth = depth.saturating_sub(1);
                if depth == 0 && at != text.len() - 1 {
                    return false;
                }
            }
            _ => {}
        }
    }
    true
}
